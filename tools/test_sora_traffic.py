r"""
ТЕСТЫ УЧЁТА ТРАФИКА
====================

ЗАЧЕМ ТАК СЛОЖНО
-----------------
Учёт трафика — часть SORA, из которой потом уходит решение.
Ошибка здесь не «VPN не подключится», а «клиенту выставят счёт не за
то, что он скачал». Это хуже: ошибку не видно сразу.

Поэтому здесь проверяется не «работает ли», а совпадает ли счётчик
с тем, что было на самом деле, — на ручных примерах, где ответ
известен заранее.

ЧТО ПОДМЕНЯЕТСЯ
---------------
Системные вызовы `iptables` не работают вне Linux. Тест подменяет
две функции — чтение счётчиков и установку правил — на собственные,
и прогоняет через них настоящий код накопления.

ЧТО ПРОВЕРЯЕТСЯ
---------------
    1. Разбор конфига: находит людей, не находит отозванных
    2. Накопление: считается разница, а не абсолютное значение
    3. Сброс счётчика: перезапуск службы не ломает учёт
    4. Лимит: превышение помечает человека, но НЕ удаляет
    5. Смена месяца: старый месяц сохраняется, новый начинается с нуля
    6. CSV: по строке на человека на месяц
    7. Человек без лимита: считается, но не отключается

ЗАПУСК
------
    python test_sora_traffic.py

КОД ВОЗВРАТА
------------
0 — все проверки пройдены
1 — есть расхождения
"""
