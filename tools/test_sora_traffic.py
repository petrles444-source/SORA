def поставить_подмену(st, счётчики):
    """Подменяет работу с iptables и возвращает словарь счётчиков."""
    st.опросить_счётчики = lambda: dict(счётчики)
    st.поставить_счётчики = lambda люди: True
    return счётчики


def базовый_опрос(st, счётчики):
    """Первый опрос месяца: только запоминает базу, ничего не прибавляет.

    Так устроен правильный учёт: счётчики iptables живут, пока жива
    служба, и при смене месяца обычно НЕ обнуляются. Если бы первый
    замер нового месяца прибавлял разницу «прошлый месяц минус ноль»,
    каждому выставлялся бы счёт вдвое больше настоящего.
    """
    ст = поставить_подмену(st, счётчики)
    st.опрос()
    return ст


def свежие_пути():
    база = tempfile.mkdtemp(prefix="sora_traffic_t_")
    конфиг_каталог = os.path.join(база, "etc")
    данные = os.path.join(база, "var")
    os.makedirs(конфиг_каталог)
    os.makedirs(данные)
    with open(os.path.join(конфиг_каталог, "server.conf"), "w",
              encoding="utf-8") as f:
        f.write(КОНФИГ)
    return {"база": база, "конфиг_каталог": конфиг_каталог, "данные": данные}


# ══════════════════════════════════════════════════════════════
#  1. Разбор конфига
# ══════════════════════════════════════════════════════════════
def тест_разбор():
    п = свежие_пути()
    st = загрузить(п)
    люди, ошибка = st.загрузить_людей()

    if ошибка:
        записать("разбор: конфиг читается", False, ошибка)
        return st, п
    if set(люди) != {"ivan", "masha"}:
        записать("разбор: найдены оба человека", False,
                 "найдено %s" % sorted(люди))
        return st, п

    ок = True
    for ник, ip in (("ivan", "10.77.0.2/32"), ("masha", "10.77.0.3/32")):
        if люди[ник]["ip"] != ip:
            ок = False
        if not люди[ник]["preshared_key"]:
            ок = False
    записать("разбор: имена и адреса на месте", ок,
             "" if ок else "разбор неверен: %s" % люди)
    return st, п


# ══════════════════════════════════════════════════════════════
#  2. Накопление считается разницей, а не абсолютным значением
# ══════════════════════════════════════════════════════════════
def тест_накопление():
    п = свежие_пути()
    st = загрузить(п)

    подмена = {"10.77.0.2": 0, "10.77.0.3": 0}
    ст = базовый_опрос(st, подмена)

    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    if сост.get("users", {}).get("ivan", {}).get("bytes") != 0:
        записать("накопление: базовый замер не прибавляет", False,
                 "получено %s" % сост.get("users", {}).get("ivan"))
        return
    записать("накопление: базовый замер не прибавляет", True)

    # второй замер при том же счётчике тоже должен дать ноль
    st.опрос()
    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    if сост["users"]["ivan"]["bytes"] == 0:
        записать("накопление: повтор без трафика даёт ноль", True)
    else:
        записать("накопление: повтор без трафика даёт ноль", False,
                 "получено %d" % сост["users"]["ivan"]["bytes"])

    # ivan скачал 10 ГБ, masha — 1 ГБ
    подмена["10.77.0.2"] = 10 * ГБ
    подмена["10.77.0.3"] = 1 * ГБ
    st.опрос()
    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    б = сост["users"]["ivan"]["bytes"]
    if б != 10 * ГБ:
        записать("накопление: первый замер учтён", False,
                 "ожидалось %d, получено %d" % (10 * ГБ, б))
        return
    записать("накопление: первый замер учтён", True)

    # ivan скачал ещё 5 ГБ. Счётчик показывает 15 ГБ, но в накопление
    # должно попасть только 5 — иначе получится 15 ГБ вместо 10.
    подмена["10.77.0.2"] = 15 * ГБ
    st.опрос()
    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    б = сост["users"]["ivan"]["bytes"]
    if б != 15 * ГБ:
        записать("накопление: считается разница, а не сумма", False,
                 "ожидалось %d (15 ГБ), получено %d" % (15 * ГБ, б))
    else:
        записать("накопление: считается разница, а не сумма", True)


# ══════════════════════════════════════════════════════════════
#  3. Сброс счётчика не ломает учёт и не даёт отрицательных значений
# ══════════════════════════════════════════════════════════════
def тест_сброс_счётчика():
    п = свежие_пути()
    st = загрузить(п)

    подмена = {"10.77.0.2": 0, "10.77.0.3": 0}
    базовый_опрос(st, подмена)

    подмена["10.77.0.2"] = 20 * ГБ
    st.опрос()

    # служба перезапустилась, счётчик обнулился; человек скачал ещё 2 ГБ
    подмена["10.77.0.2"] = 2 * ГБ
    st.опрос()

    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    б = сост["users"]["ivan"]["bytes"]
    сбросы = сост["users"]["ivan"].get("resets", 0)

    if б < 0:
        записать("сброс счётчика: нет отрицательных значений", False,
                 "получено %d" % б)
        return
    записать("сброс счётчика: нет отрицательных значений", True)

    if сбросы != 1:
        записать("сброс счётчика: событие зафиксировано", False,
                 "сбросов %d, ждали 1" % сбросы)
    else:
        записать("сброс счётчика: событие зафиксировано", True)

    if б != 22 * ГБ:
        записать("сброс счётчика: потерянное не задваивается", False,
                 "ожидалось %d (22 ГБ), получено %d" % (22 * ГБ, б))
    else:
        записать("сброс счётчика: потерянное не задваивается", True)


# ══════════════════════════════════════════════════════════════
#  4. Лимит помечает человека, но не удаляет
# ══════════════════════════════════════════════════════════════
def тест_лимит():
    п = свежие_пути()
    st = загрузить(п)

    # лимит 5 ГБ для ivan, у masha лимита нет вовсе
    st.записать_json(st.ПУТЬ_ЛИМИТЫ, {"ivan": {"gb": 5.0}})

    подмена = {"10.77.0.2": 0, "10.77.0.3": 0}
    базовый_опрос(st, подмена)

    подмена["10.77.0.2"] = 6 * ГБ      # превысил
    подмена["10.77.0.3"] = 50 * ГБ     # без лимита
    st.опрос()

    блок = st.прочитать_json(st.ПУТЬ_БЛОК, [])
    if "ivan" not in блок:
        записать("лимит: превышение помечает человека", False,
                 "в blocked.json: %s" % блок)
    else:
        записать("лимит: превышение помечает человека", True)

    if "masha" in блок:
        записать("лимит: без лимита не отключается", False,
                 "masha попала в blocked.json без лимита")
    else:
        записать("лимит: без лимита не отключается", True)

    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    if "ivan" not in сост.get("users", {}):
        записать("лимит: человек НЕ удалён из учёта", False,
                 "ivan пропал из состояния — удаление недопустимо")
    else:
        записать("лимит: человек НЕ удалён из учёта", True)

    # повторный опрос не должен ругаться снова и не должен терять учёт
    st.опрос()
    сост2 = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    if сост2.get("users", {}).get("ivan", {}).get("bytes") == 6 * ГБ:
        записать("лимит: повторный опрос стабилен", True)
    else:
        записать("лимит: повторный опрос стабилен", False,
                 "счётчик поехал: %s"
                 % сост2.get("users", {}).get("ivan", {}).get("bytes"))


