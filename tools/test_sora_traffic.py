#  5. Смена месяца
# ══════════════════════════════════════════════════════════════
def тест_смена_месяца():
    п = свежие_пути()
    st = загрузить(п)

    подмена = {"10.77.0.2": 0, "10.77.0.3": 0}
    базовый_опрос(st, подмена)

    подмена["10.77.0.2"] = 7 * ГБ
    st.опрос()

    # притворяемся, что прошёл месяц
    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    сост["month"] = "1999-01"
    st.записать_json(st.ПУТЬ_СОСТОЯНИЕ, сост)

    подмена["10.77.0.2"] = 1 * ГБ
    st.опрос()

    сост = st.прочитать_json(st.ПУТЬ_СОСТОЯНИЕ, {})
    б = сост.get("users", {}).get("ivan", {}).get("bytes")

    if б is None:
        записать("смена месяца: новый месяц с нуля", False,
                 "ivan пропал из нового месяца")
    elif б == 0:
        записать("смена месяца: новый месяц с нуля", True)
    else:
        записать("смена месяца: новый месяц с нуля", False,
                 "в новом месяце уже %d байт" % б)

    файлы = os.listdir(st.ПУТЬ_ИСТОРИЯ) if os.path.isdir(st.ПУТЬ_ИСТОРИЯ) else []
    if "1999-01.json" not in файлы:
        записать("смена месяца: прошлый месяц сохранён", False,
                 "в истории: %s" % файлы)
    else:
        записать("смена месяца: прошлый месяц сохранён", True)


# ══════════════════════════════════════════════════════════════
#  6. CSV: по строке на человека на месяц
# ══════════════════════════════════════════════════════════════
def тест_csv():
    п = свежие_пути()
    st = загрузить(п)

    подмена = {"10.77.0.2": 0, "10.77.0.3": 0}
    базовый_опрос(st, подмена)
    подмена["10.77.0.2"] = 3 * ГБ
    подмена["10.77.0.3"] = 1500
    st.опрос()

    if not os.path.exists(st.ПУТЬ_CSV):
        записать("csv: файл создан", False)
        return
    записать("csv: файл создан", True)

    строки = io.open(st.ПУТЬ_CSV, encoding="utf-8").read().strip().split("\n")
    if len(строки) != 3:
        записать("csv: шапка + два человека", False,
                 "строк %d" % len(строки))
        return
    записать("csv: шапка + два человека", True)

    ivan = [s for s in строки if ",ivan," in s]
    if not ivan:
        записать("csv: ivan присутствует", False)
        return
    байты = int(ivan[0].split(",")[2])
    if байты != 3 * ГБ:
        записать("csv: байты верные", False,
                 "ожидалось %d, получено %d" % (3 * ГБ, байты))
    else:
        записать("csv: байты верные", True)


