ГБ = 1 << 30

ИТОГИ = []


def записать(имя, годно, деталь=""):
    ИТОГИ.append((годно, имя, деталь))
    знак = "[ок]" if годно else "[!!]"
    строка = "  %s %s" % (знак, имя)
    if not годно and деталь:
        строка += "\n         %s" % деталь
    print(строка)


def загрузить(пути):
    """Грузит модуль, подставляя пути файлов во временный каталог."""
    spec = importlib.util.spec_from_file_location("sora_traffic_t", МОДУЛЬ)
    st = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(st)
    st.КАТ_СЕРВЕРА = пути["конфиг_каталог"]
    st.ПУТЬ_КОНФ = os.path.join(пути["конфиг_каталог"], "server.conf")
    st.ПУТЬ_ЛИМИТЫ = os.path.join(пути["конфиг_каталог"], "quotas.json")
    st.ПУТЬ_БЛОК = os.path.join(пути["конфиг_каталог"], "blocked.json")
    st.КАТ_ДАННЫХ = пути["данные"]
    st.ПУТЬ_СОСТОЯНИЕ = os.path.join(пути["данные"], "traffic.json")
    st.ПУТЬ_CSV = os.path.join(пути["данные"], "traffic.csv")
    st.ПУТЬ_ИСТОРИЯ = os.path.join(пути["данные"], "history")
    return st


