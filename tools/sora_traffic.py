# ══════════════════════════════════════════════════════════════
#  Работа с файлами — с заменой через временный, чтобы упавшая
#  система не оставила обрезанный JSON. Это единственная защита
#  от потери состояния при сбое питания в неподходящий момент.
# ══════════════════════════════════════════════════════════════
def прочитать_json(путь, по_умолчанию):
    if not os.path.exists(путь):
        return по_умолчанию
    try:
        with open(путь, encoding="utf-8") as f:
            return json.load(f)
    except (ValueError, OSError):
        # Битый файл не молчим: возвращаем пустое и оставляем битый
        # на месте, чтобы его можно было посмотреть глазами.
        return по_умолчанию


def записать_json(путь, данные):
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    врем = путь + ".tmp"
    with open(врем, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)
        f.flush()
        os.fsync(f.fileno())
    os.replace(врем, путь)


def взять_блокировку():
    """Не дать двум опросам писать в состояние одновременно.

    ЗАЧЕМ. Крон запускает опрос каждые 5 минут. Если предыдущий
    завис — а он зависнет, если iptables подвиснет — следующий
    стартует, не дождавшись. Оба прочитают одно и то же состояние,
    оба прибавят одну и ту же разницу, и кто-то из них перезапишет
    чужой результат.

    Само по себе это не удваивает счёт: оба считают одну разницу.
    Но теряется целый интервал, а «не предсказуемо на пяти минутах» —
# это ровно тот сорт поломки, который потом не воспроизвести.

    Блокировка неблокирующая: если кто-то уже работает, второй
    тихо выходит с кодом 0. Ждать незачем — через минуту придёт
    следующий.
    """
    путь = os.path.join(КАТ_ДАННЫХ, "poll.lock")
    try:
        os.makedirs(КАТ_ДАННЫХ, mode=0o700, exist_ok=True)
    except OSError:
        return True          # не смогли создать каталог — не блокируем

    try:
        fd = os.open(путь, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        # проверяем возраст: если замок старше часа, он мёртвый
        try:
            возраст = time.time() - os.path.getmtime(путь)
            if возраст < 3600:
                return False
            os.remove(путь)       # снять мёртвый замок
            fd = os.open(путь, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        except OSError:
            return False
    except OSError:
        return True

    try:
        os.write(fd, str(os.getpid()).encode())
        os.close(fd)
    except OSError:
        pass
    return True


def отпустить_блокировку():
    путь = os.path.join(КАТ_ДАННЫХ, "poll.lock")
    try:
        os.remove(путь)
    except OSError:
        pass


def человек_человека(байты):
    """Байты в строку, читаемую глазом."""
    б = float(байты)
    for ед, название in ((1 << 30, "ГБ"), (1 << 20, "МБ"), (1 << 10, "КБ")):
        if б >= ед:
            return "%.2f %s" % (б / ед, название)
    return "%d Б" % б


# ══════════════════════════════════════════════════════════════
#  Кто есть кто: сопоставление адреса и имени человека
# ══════════════════════════════════════════════════════════════
RX_СЕКЦИЯ = re.compile(r"^\[(?P<секция>[^\]]+)\]\s*$")
RX_ПОЛЕ = re.compile(r"^(?P<ключ>[A-Za-z0-9_]+)\s*=\s*(?P<значение>.*)$")




def разобрать_конфиг(текст):
    """Возвращает {имя_человека: {ip, public_key, preshared_key}}.

    Имя человека берётся из комментария вида
    ``# --- ivan  (ноутбук HP)``. Формат этого файла — единственный
    известный идентификатор.

    ДВЕ ОШИБКИ БЫЛИ В ПЕРВЫХ ВЕРСИЯХ, обе приводили к одному и тому же
    молчаливому обнулению счётчиков, а значит — к расхождению
    отчёта с тем, что видно в логах провайдера.

    Первая: все строки, начинающиеся с ``#``, отбрасывались до того,
    как читалось имя. Список людей оказывался пустым.

    Вторая, исправленная версия: на строке ``[Peer]`` вызывался
    общий сброс, который обнулял не только поля, но и имя, только
    что объявленное комментарием на строкой выше. Имя стиралось раньше,
    чем набирались к нему поля, — и человек снова не попадал в учёт.

    Поэтому сброс полей и сброс имени разведены: имя живёт от своего
    комментария до следующего.
    """
    люди = {}
    накоплено = {}
    имя = ""

    def сохранить(сброс_имени=False):
        """Кладёт собранные поля в словарь под текущим именем."""
        nonlocal накоплено, имя
        чистое = имя.split("(")[0].strip()
        if чистое and накоплено.get("PublicKey"):
            люди[чистое] = {
                "ip": накоплено.get("AllowedIPs", ""),
                "public_key": накоплено.get("PublicKey", ""),
                "preshared_key": накоплено.get("PresharedKey", ""),
            }
        накоплено = {}
        if сброс_имени:
            имя = ""

    for строка in текст.splitlines():
        строка = строка.rstrip()

        # 1. Комментарий. Проверяем РАНЬШЕ, чем отбрасываем.
        обр = строка.lstrip()
        if обр.startswith("#"):
            тело = обр.lstrip("#").strip()
            if тело.startswith("---"):
                # закрываем ПРЕДЫДУЩЕГО человека и начинаем нового
                сохранить(сброс_имени=True)
                имя = тело[3:].strip()
            continue

        # 2. Хвостовой комментарий убираем
        чистая = строка.split("#")[0].strip()
        if not чистая:
            continue

        # 3. Секция. На [Peer] закрываем предыдущего, но имя
        #    текущего НЕ трогаем — оно объявлено строкой выше.
        m = RX_СЕКЦИЯ.match(чистая)
        if m:
            if m.group("секция").strip() == "Peer":
                сохранить()
            continue

        # 4. Поле
        m = RX_ПОЛЕ.match(чистая)
        if m:
            накоплено[m.group("ключ")] = m.group("значение").strip()

    сохранить()
    return люди


def загрузить_людей():
    """Люди из конфига сервера. Это источник правды на сервере."""
    if not os.path.exists(ПУТЬ_КОНФ):
        return {}, "нет %s" % ПУТЬ_КОНФ
    try:
        with open(ПУТЬ_КОНФ, encoding="utf-8") as f:
            текст = f.read()
    except OSError as e:
        return {}, str(e)
    return разобрать_конфиг(текст), None


# ══════════════════════════════════════════════════════════════
#  Счётчики iptables
# ══════════════════════════════════════════════════════════════
RX_СЧЁТЧИК = re.compile(
    r"^\s*(?P<пакеты>\d+)\s+"
    r"(?P<байты>\d+)\s+"
    r"\S+\s+"          # target
    r"\S+\s+"          # prot
    r"\S+\s+"          # opt
    r"\S+\s+"          # in
    r"\S+\s+"          # out
    r"(?P<источник>[\d.]+/\d+|\S+)\s+"   # source
    r"\S+\s*"          # destination
)


def опросить_счётчики():
    """Читает накопленные байты по каждому адресу из цепочки.

    Возвращает {ip: байты}. Ошибка — поднимается вызывающим.

    ──────────────────────────────────────────────────────────────────
    БЫЛ БАГ, НАЙДЕННЫЙ НА ЖИВОМ СЕРВЕРЕ 15.10.2026.

    Код брал колонку «правило» и искал в ней `-s 10.77.0.2/32`.
    Но `iptables -L` такого текста НЕ ВЫВОДИТ. Он печатает
    источник отдельной колонкой:

        Chain SORA-TRAFFIC (1 references)
        num  pkts  bytes target prot opt in out source        destination
        1       0      0 ACCEPT 0    --  *  *   10.77.0.2   0.0.0.0/0

    Слова `-s` там нет вообще, поэтому поиск всегда давал пусто,
    и poll честно возвращал код 2: «счётчики не установлены».
    Правила при этом были, самопроверка их видела и говорила «ок».

    То есть два разных инструмента смотрели на одно и то же
    и делали противоположные выводы.

    Теперь разбираем ПОЗИЦИОННО. Формат `iptables -L -n -v -x`:

        pkts bytes target prot opt in out source destination

    Восемь колонок после двух числовых. Источник — восьмая.
    `--line-numbers` НЕ используется: он добавляет лишний столбец
    в начало и сдвигает всё.
    ──────────────────────────────────────────────────────────────────
    """
    p = subprocess.run(
        ["iptables", "-t", "filter", "-L", ЦЕПОЧКА, "-n", "-v", "-x"],
        capture_output=True, text=True, errors="replace")

    if p.returncode != 0:
        raise RuntimeError("iptables не отдал счётчики: %s"
                           % (p.stderr.strip() or "цепочки нет"))

    счётчики = {}
    for строка in p.stdout.splitlines():
        m = RX_СЧЁТЧИК.match(строка)
        if not m:
            continue
        ip = m.group("источник").split("/")[0]
        if not ip or ip in ("*", "0.0.0.0/0"):
            continue
        try:
            байты = int(m.group("байты"))
        except (ValueError, TypeError):
            continue
        счётчики[ip] = счётчики.get(ip, 0) + байты

    if not счётчики:
        raise RuntimeError(
            "в цепочке %s нет ни одного счётчика — правила не установлены?"
            % ЦЕПОЧКА)
    return счётчики


def поставить_счётчики(люди):
    """Вешает правила со счётчиками на каждого человека."""
    subprocess.run(["iptables", "-t", "filter", "-N", ЦЕПОЧКА],
                   capture_output=True)
    # цепочка должна вызываться из FORWARD
    if subprocess.run(["iptables", "-t", "filter", "-C", "FORWARD",
                       "-j", ЦЕПОЧКА], capture_output=True).returncode != 0:
        subprocess.run(["iptables", "-t", "filter", "-I", "FORWARD", "1",
                        "-j", ЦЕПОЧКА], capture_output=True)

    for имя, данные in люди.items():
        ip = данные.get("ip", "").split("/")[0].strip()
        if not ip:
            continue
        уже = subprocess.run(
            ["iptables", "-t", "filter", "-C", ЦЕПОЧКА,
             "-s", ip, "-j", "ACCEPT"], capture_output=True)
        if уже.returncode != 0:
            subprocess.run(["iptables", "-t", "filter", "-A", ЦЕПОЧКА,
                            "-s", ip, "-j", "ACCEPT"], capture_output=True)
    return True


def снести_счётчики():
    subprocess.run(["iptables", "-t", "filter", "-D", "FORWARD",
                    "-j", ЦЕПОЧКА], capture_output=True)
    subprocess.run(["iptables", "-t", "filter", "-F", ЦЕПОЧКА],
                   capture_output=True)
    subprocess.run(["iptables", "-t", "filter", "-X", ЦЕПОЧКА],
                   capture_output=True)


# ══════════════════════════════════════════════════════════════
#  Состояние и месячный переход
# ══════════════════════════════════════════════════════════════
def текущий_месяц():
    return datetime.date.today().strftime("%Y-%m")


def новое_состояние():
    """Пустое состояние нового месяца.

    Поле baseline означает: «счётчики уже прочитаны хотя бы раз, и
    накопленное — это трафик сверх них». Пока baseline нет, первый
    замер ТОЛЬКО запоминает текущие значения счётчиков и не прибавляет
    ничего.

    Без этого на стыке месяцев весь прошлый месяц зачислялся бы заново:
    счётчик iptables живёт, пока жива служба, и при смене месяца он
    обычно НЕ обнуляется. Новое состояние начинается с нуля, но
    счётчик по-прежнему показывает прошлый месяц — и разница
    «прошлый месяц минус ноль» равна целому прошлому месяцу.

    Из-за этого с первого же месяца объём у каждого удваивался бы,
    и счёт сошёлся бы с логом провайдера только у одного человека.
    """
    return {
        "month": текущий_месяц(),
        "baseline": False,
        "users": {},        # ник -> {bytes, last_counter, resets, first_seen}
        "created": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }


def опрос(тихо=False):
    """Главный цикл: опросить, накопить, применить лимиты."""
    # два опроса одновременно портили бы состояние: оба прочитают
    # одно и то же и перезапишут результат друг друга, потеряв интервал
    if not взять_блокировку():
        if not тихо:
            print(СЕР + "  Другой опрос уже идёт. Выхожу." + СБР)
        return 0
    try:
        return _опрос_под_блокировкой(тихо)
    finally:
        отпустить_блокировку()


def _опрос_под_блокировкой(тихо=False):
    """Собственно опрос. Блокировка уже взята."""
    люди, ошибка = загрузить_людей()
    if ошибка:
        print("%sНе могу прочитать конфиг: %s%s" % (КРАС, ошибка, СБР))
        return 2

    if not люди:
        if not тихо:
            print(СЕР + "  В конфиге нет ни одного пользователя." + СБР)
        return 0

    try:
        поставить_счётчики(люди)
        счётчики = опросить_счётчики()
    except RuntimeError as e:
        print("%sУчёт не работает: %s%s" % (КРАС, e, СБР))
        return 2

    состояние = прочитать_json(ПУТЬ_СОСТОЯНИЕ, None)
    if not состояние or "users" not in состояние:
        состояние = новое_состояние()
    elif состояние.get("month") != текущий_месяц():
        закрыть_месяц(состояние)
        состояние = новое_состояние()

    # Первый замер нового месяца базовой линии не имеет.
    не_есть_базы = not состояние.get("baseline", False)

    лимиты = прочитать_json(ПУТЬ_ЛИМИТЫ, {})
    блок = set(прочитать_json(ПУТЬ_БЛОК, []))

    превышены = []
    сбросы = []

    for имя, данные in люди.items():
        ip = данные.get("ip", "").split("/")[0].strip()
        if not ip:
            continue
        текущий = счётчики.get(ip, 0)
        запись = состояние["users"].setdefault(
            имя, {"bytes": 0, "last_counter": 0, "resets": 0,
                  "first_seen": datetime.datetime.now().strftime("%Y-%m-%d")})

        было = запись.get("last_counter", 0)

        if не_есть_базы:
            # Первый замер месяца: только запоминаем, куда мы встали.
            # Прибавлять нечего — иначе на стыке месяцев весь прошлый
            # месяц попал бы в новый второй раз.
            запись["last_counter"] = текущий
        elif текущий >= было:
            запись["bytes"] = запись.get("bytes", 0) + (текущий - было)
            запись["last_counter"] = текущий
        else:
            # счётчик уменьшился: служба перезапустилась и обнулила его.
            # Считаем от нуля, но помечаем: потерянный кусок трафика
            # не восстановить, и об этом надо знать при сверке.
            запись["bytes"] = запись.get("bytes", 0) + текущий
            запись["last_counter"] = текущий
            запись["resets"] = запись.get("resets", 0) + 1
            сбросы.append(имя)

        # лимит
        лимит = лимиты.get(имя)
        if isinstance(лимит, dict):
            гб = лимит.get("gb")
        else:
            гб = лимит
        if гб:
            предел = float(гб) * (1 << 30)
            if запись["bytes"] > предел and имя not in блок:
                блок.add(имя)
                превышены.append((имя, запись["bytes"], предел))

    # База появилась — с этого момента считаем разницы.
    состояние["baseline"] = True

    записать_json(ПУТЬ_СОСТОЯНИЕ, состояние)
    записать_json(ПУТЬ_БЛОК, sorted(блок))
    написать_csv(состояние)

    if тихо:
        показать_отчёт(состояние, лимиты, блок)

    for имя, _б, _п in превышены:
        print("%sЛИМИТ ПРЕВЫШЕН: %s — %s из %s ГБ%s"
              % (КРАС, имя,
                 человек_человека(_б), _п / (1 << 30), СБР))
        print("  Он отключён от туннеля и НЕ УДАЛЁН. Вернуть:")
        print("      sora_traffic.py unblock %s" % имя)
    for имя in сбросы:
        print("%sВнимание: счётчик %s обнулён (перезапуск службы). "
              "Кусок трафика потерян и в отчёт не попадёт.%s"
              % (ЖЁЛ, имя, СБР))

    return 1 if превышены else 0


