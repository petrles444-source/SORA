# -*- coding: utf-8 -*-
r"""
SORA — УЧЁТ ТРАФИКА И ЛИМИТЫ
============================

ЗАЧЕМ
-----
На сервере есть месячный лимит трафика: 4000 ГБ. Без учёта
непонятно, сколько израсходовано и сколько останется, и один
человек может съесть весь объём. Поэтому трафик меряется
точно по каждому, и отдельно взятый человек ограничивается.

Этот модуль измеряет трафик по каждому пользователю, ведёт историю
помесячно и отключает того, кто превысил лимит.

ПОЧЕМУ НЕ ЧЕРЕЗ `wg show`
--------------------------
`wg show` показывает счётчики только у WireGuard и только у того,
кто эти счётчики поддерживает. Наш вариант — `amnezia-awg-go`,
а счётчики в нём ведут себя по-разному в разных версиях.

Поэтому считаем через iptables: это не зависит от реализации VPN
вообще. Один и тот же метод посчитает трафик и для amnezia-awg-go,
и для обычного WireGuard, и для любого будущего варианта.

КАК СЧИТАЕТСЯ
-------------
На каждого пользователя вешается счётчик байтов в цепочке FORWARD.
Счётчики НЕ обнуляются — вместо этого запоминается последнее
прочитанное значение, и трафик считается как разница.

Почему не обнулять: команда обнуления гоняется с работающим VPN,
между чтением и обнулением может пройти пакет — и он будет учтён
дважды или потерян. Разница абсолютных значений такой ошибки не
даёт.

Если счётчик вдруг уменьшился (перезапустилась служба и счётчики
обнулились), это отслеживается отдельно: занижение не приводит к
отрицательному трафику, а просто помечается как событие сброса.

ЧТО ГДЕ ЛЕЖИТ
-------------
    /etc/sora/quotas.json       лимиты, задаёте вы
    /etc/sora/blocked.json      кто отключён по лимиту
    /var/lib/sora/traffic.json  накопленные счётчики (состояние)
    /var/lib/sora/traffic.csv   выгрузка в таблицу
    /var/lib/sora/history/      помесячные срезы, не теряются

ЛИМИТЫ
------
По умолчанию лимитов нет — трафик только считается. Лимит задаётся
для конкретного человека:

    sora_traffic.py limit ivan 100      # 100 ГБ в месяц
    sora_traffic.py limit ivan 100 80   # 100 ГБ, предупредить на 80

Человек, превысивший лимит, не удаляется, а помечается в
`blocked.json`. Установщик читает этот файл при пересборке
конфигурации и не включает таких людей в конфиг сервера.
Это обратимо: сняли лимит — человек вернулся.

ЗАПУСК
------
    sora_traffic.py poll                 # опросить и применить лимиты
    sora_traffic.py report               # отчёт по текущему месяцу
    sora_traffic.py csv                  # выгрузка в таблицу
    sora_traffic.py limit ivan 100       # поставить лимит
    sora_traffic.py limit --list         # показать лимиты
    sora_traffic.py unblock ivan         # снять блокировку
    sora_traffic.py reset ivan           # обнулить счётчик человеку

КРОН (ставится автоматически)
-----------------------------
    */5 * * * *  sora_traffic.py poll

ПЯТЬ МИНУТ — компромисс. Чаще точнее, но чаще и накладные расходы;
реже — крупнее пауза до отключения. На сам счёт это не влияет:
счётчик идёт по байтам и ничего не теряется между опросами,
частота определяет только скорость реакции.

КОД ВОЗВРАТА
------------
0 — всё в порядке
1 — есть превышенные лимиты (не ошибка, а факт)
2 — ошибка чтения счётчиков
"""
