def _пересобрать(строки, блок):
    """Пересобирает конфиг без указанных людей.

    Работает по границам секций: у человека в файле есть комментарий
    ``# --- имя`` и вслед за ним секция ``[Peer]`` с полями. Вырезается
    и то, и другое. Одиночный проход по строкам здесь не годится:
    имя известно только из комментария, а вырезать надо и комментарий,
    и секцию.

    Возвращает (новые_строки, имена_удалённых).
    """
    результат = []
    убрали = []
    i = 0
    n = len(строки)

    while i < n:
        стр = строки[i]
        обрезанная = стр.lstrip()

        if обрезанная.startswith("#"):
            тело = обрезанная.lstrip("#").strip()
            if тело.startswith("---"):
                имя = тело[3:].split("(")[0].strip()
                if имя in блок:
                    j = i + 1
                    # пропускаем пустые строки до заголовка секции
                    while j < n and строки[j].strip() == "":
                        j += 1
                    # сама секция и её поля — до пустой строки или конца
                    if j < n and строки[j].strip().startswith("[Peer]"):
                        j += 1
                        while j < n and строки[j].strip() != "":
                            j += 1
                        убрали.append(имя)
                        i = j
                        continue
            результат.append(стр)
            i += 1
            continue

        результат.append(стр)
        i += 1

    return результат, убрали


def _атомарно_записать(путь, текст):
    """Заменяет файл целиком, через временный и rename.

    Если питание пропадёт посреди записи, останется либо старый файл,
    либо новый — но не оборванный. Для конфига работающего VPN это
    разница между «VPN работает» и «сервер не грузится».
    """
    врем = путь + ".new"
    with open(врем, "w", encoding="utf-8") as f:
        f.write(текст)
        f.flush()
        os.fsync(f.fileno())
    os.replace(врем, путь)
    os.chmod(путь, 0o600)


def применить_блокировки(тихо=False):
    """Убирает из живого конфига тех, кто превысил лимит.

    Здесь правится файл, который прямо сейчас читает работающий VPN,
    поэтому порядок строгий:

      1. резервная копия ДО любых изменений;
      2. новый текст собирается целиком и проверяется разбором;
      3. если хоть один заблокированный остался в тексте — отказ,
         старый файл не тронут;
      4. если ничего не изменилось — VPN не перезапускается зря;
      5. после записи проверяется, поднялась ли служба; если нет —
         конфиг возвращается обратно.

    Возвращает (сколько_убрали, сообщение).
    """
    if not os.path.exists(ПУТЬ_КОНФ):
        return 0, "нет %s" % ПУТЬ_КОНФ

    блок = set(прочитать_json(ПУТЬ_БЛОК, []))
    if not блок:
        if not тихо:
            print("%sЗаблокированных нет. Конфиг не тронут.%s" % (СЕР, СБР))
        return 0, "заблокированных нет"

    with open(ПУТЬ_КОНФ, encoding="utf-8") as f:
        исходный = f.read()

    новые, убрали = _пересобрать(исходный.splitlines(), блок)

    if not убрали:
        if not тихо:
            print(ЖЁЛ + "  Заблокированных в конфиге нет. Ничего не менял."
                  + СБР)
        return 0, "в конфиге их не было"

    текст_новый = "\n".join(новые) + "\n"

    # Проверка 1: заблокированный не должен просочиться
    проверка = разобрать_конфиг(текст_новый)
    просочились = [н for н in проверка if н in блок]
    if просочились:
        if not тихо:
            print("%sОТКАЗ: в новом тексте остались %s. Файл не тронут.%s"
                  % (КРАС, ", ".join(просочились), СБР))
        return 0, "проверка не пройдена"

    # Проверка 2: убирать всех нельзя — VPN без людей бессмыслен,
    # но это состояние надо назвать вслух
    # (проверка 1 уже гарантирует, что там остались живые)

    with open(ПУТЬ_КОНФ + ".bak", "w", encoding="utf-8") as f:
        f.write(исходный)

    _атомарно_записать(ПУТЬ_КОНФ, текст_новый)

    if not тихо:
        print("%sУбрано из конфига: %s%s" % (ЗЕЛ, ", ".join(убрали), СБР))
        print(СЕР + "  копия прежнего: %s.bak" % ПУТЬ_КОНФ + СБР)

    p = subprocess.run(["systemctl", "reload-or-restart", "amnezia-awg-go"],
                       capture_output=True)
    if p.returncode == 0:
        if not тихо:
            print("%sVPN перезапущен.%s" % (ЗЕЛ, СБР))
        return len(убрали), "применено"

    # не поднялось — возвращаем как было, чтобы не остаться без VPN
    with open(ПУТЬ_КОНФ, "w", encoding="utf-8") as f:
        f.write(исходный)
    os.chmod(ПУТЬ_КОНФ, 0o600)
    if not тихо:
        print("%sПерезапуск не удался. Конфиг возвращён обратно.%s"
              % (КРАС, СБР))
    return 0, "перезапуск не удался, откачено"


def _найти_блок(строки, имя):
    """Вытаскивает из конфига блок одного человека.

    Блок — это комментарий ``# --- имя`` и следующая за ним секция
    ``[Peer]`` с полями. Возвращает список строк или None.
    """
    n = len(строки)
    for i, стр in enumerate(строки):
        обрезанная = стр.lstrip()
        if not обрезанная.startswith("#"):
            continue
        тело = обрезанная.lstrip("#").strip()
        if not тело.startswith("---"):
            continue
        if тело[3:].split("(")[0].strip() != имя:
            continue

        блок = [стр]
        j = i + 1
        while j < n and строки[j].strip() == "":
            j += 1
        if j < n and строки[j].strip().startswith("[Peer]"):
            блок.append(строки[j])
            j += 1
            while j < n and строки[j].strip() != "":
                блок.append(строки[j])
                j += 1
        return блок
    return None


def _вставить_перед_концом(строки, блок):
    """Вставляет блок человека в конец списка секций.

    Ставить надо после последней секции [Peer], иначе блок окажется
    внутри чужой секции и конфиг перестанет разбираться.
    """
    if not строки:
        return list(блок)
    вставлено = False
    результат = []
    i = 0
    n = len(строки)
    while i < n:
        стр = строки[i]
        результат.append(стр)
        if стр.lstrip().startswith("[Peer]"):
            # пробегаем поля текущей секции
            j = i + 1
            while j < n and строки[j].strip() != "":
                результат.append(строки[j])
                j += 1
            # если дальше есть ещё секция — вставим перед ней
            if j < n and строки[j].strip().startswith("["):
                if not вставлено:
                    результат.extend([""] + блок)
                    вставлено = True
            i = j
            continue
        i += 1

    if not вставлено:
        # секций [Peer] не было вовсе — дописываем в конец
        результат.extend([""] + блок)
    return результат


def вернуть_блокировку(ник):
    """Возвращает человека в конфиг сервера.

    БЕРЁТ ЕГО БЛОК ИЗ РЕЗЕРВНОЙ КОПИИ И ВСТАВЛЯЕТ В ТЕКУЩИЙ КОНФИГ.

    Первый вариант делал наоборот: читал копию и вырезал из неё
    человека. Ошибка была неочевидной — на копии этот человек ещё
    был, так что вырезать оттуда значило гарантированно НЕ вернуть
    его, а тихо получить конфиг без него же.

    Копия берётся как источник блока, а не как готовый файл: если
    после последнего применения в конфиге появились другие люди,
    замена файла целиком их бы потеряла.
    """
    блок = set(прочитать_json(ПУТЬ_БЛОК, []))
    if ник not in блок:
        print()
        print(ЖЁЛ + "  «%s» и так не заблокирован." % ник + СБР)
        print()
        return

    if not os.path.exists(ПУТЬ_КОНФ):
        print(КРАС + "  Нет %s" % ПУТЬ_КОНФ + СБР)
        return

    копия = ПУТЬ_КОНФ + ".bak"
    if not os.path.exists(копия):
        print()
        print(КРАС + "  Нет резервной копии %s" % копия + СБР)
        print(СЕР + "  Вернуть человека может только пересборка конфига"
                    " на вашем компьютере:" + СБР)
        print("      python sora_keys.py server --out server/server.conf")
        print()
        return

    with open(копия, encoding="utf-8") as f:
        строки_копии = f.read().splitlines()
    with open(ПУТЬ_КОНФ, encoding="utf-8") as f:
        строки = f.read().splitlines()

    блок_человека = _найти_блок(строки_копии, ник)
    if not блок_человека:
        print()
        print(КРАС + "  В резервной копии человека «%s» нет." % ник + СБР)
        print(СЕР + "  Вернуть можно только пересборкой конфига на ПК." + СБР)
        print()
        return

    новые = _вставить_перед_концом(строки, блок_человека)
    текст = "\n".join(новые) + "\n"

    # страховка: собранный конфиг обязан разбираться и содержать человека
    собранное = разобрать_конфиг(текст)
    if собранное is None or ник not in собранное:
        print(КРАС + "  Собранный конфиг не проходит проверку. Отказ." + СБР)
        print(ЖЁЛ + "  Файл не тронут." + СБР)
        return

    # и не должен потерять тех, кто оставался
    были = set(разобрать_конфиг("\n".join(строки) + "\n") or {})
    потеряны = были - set(собранное)
    if потеряны:
        print(КРАС + "  При вставке потеряны: %s. Отказ." % ", ".join(потеряны)
              + СБР)
        print(ЖЁЛ + "  Файл не тронут." + СБР)
        return

    _атомарно_записать(ПУТЬ_КОНФ, текст)

    блок.discard(ник)
    записать_json(ПУТЬ_БЛОК, sorted(блок))

    subprocess.run(["systemctl", "reload-or-restart", "amnezia-awg-go"],
                   capture_output=True)

    print()
    print("%s%s возвращён в конфиг.%s" % (ЗЕЛ, ник, СБР))
    print(СЕР + "  VPN перезапущен." + СБР)
    print(ЖЁЛ + "  Лимит пока НЕ снят — при следующем превышении отключит снова."
          + СБР)
    print("      снять лимит:   sora_traffic.py limit %s" % ник)
    print("      поднять лимит: sora_traffic.py limit %s 200" % ник)
    print()


def main():
    """Точка входа.

    ПОРЯДОК ПРОВЕРОК ВАЖЕН И БЫЛ ОШИБОЧЕН НЕСКОЛЬКО РАЗ.

    1. Нет аргументов — показываем справку. Раньше справка
       выводилась ПОСЛЕ проверки root, и человек, запустивший
       `sora_traffic.py` без root, получал «Нужен root» вместо
       списка команд.

    2. Неизвестная команда — говорим об этом СРАЗУ. Раньше на
       опечатку выдавалось «Нужен root»: человек чинил права,
       а на самом деле опечатался в названии.

    3. Только потом проверяем root. Часть команд (отчёт, выгрузка,
       список лимитов, статус) файлы не меняют — им root не нужен.
    """
    if len(sys.argv) < 2:
        print(__doc__)
        return 1

    действие = sys.argv[1]
    арг = sys.argv[2:]

    ИЗВЕСТНЫЕ = {
        "poll", "report", "csv", "apply", "restore", "status",
        "limit", "unblock", "reset",
    }
    БЕЗ_ROOT = {"report", "csv", "limit", "status"}

    if действие not in ИЗВЕСТНЫЕ:
        похожие = [c for c in sorted(ИЗВЕСТНЫЕ) if c[0] == действие[0]]
        print()
        print(КРАС + "  Неизвестная команда: «%s»" % действие + СБР)
        if похожие:
            print(СЕР + "  Похожее: " + ", ".join(похожие) + СБР)
        print(СЕР + "  Доступны: " + ", ".join(sorted(ИЗВЕСТНЫЕ)) + СБР)
        print(СЕР + "  Подробности: sora_traffic.py  (без аргументов)"
              + СБР)
        print()
        return 1

    # geteuid есть только в Unix. На Windows его нет — и стать там
    # root всё равно невозможно, поэтому подставляем «не root».
    есть_root = (getattr(os, "geteuid", lambda: 1)() == 0)

    if not есть_root and действие not in БЕЗ_ROOT:
        print()
        print(КРАС + "  Эта команда меняет файлы — нужен root." + СБР)
        print(СЕР + "      sudo sora_traffic.py %s" % действие + СБР)
        print()
        return 1

    if действие == "poll":
        return опрос()

    if действие == "report":
        состояние = прочитать_json(ПУТЬ_СОСТОЯНИЕ, None)
        if not состояние:
            print(ЖЁЛ + "  Данных нет. Запустите: sora_traffic.py poll"
                  + СБР)
            return 1
        показать_отчёт(состояние,
                       прочитать_json(ПУТЬ_ЛИМИТЫ, {}),
                       set(прочитать_json(ПУТЬ_БЛОК, [])))
        return 0

    if действие == "csv":
        return экспорт_csv()

    if действие == "apply":
        _n, _сообщение = применить_блокировки()
        return 0

    if действие == "restore":
        if not арг:
            print()
            print(КРАС + "  Укажите имя: sora_traffic.py restore ivan"
                  + СБР)
            print()
            return 1
        вернуть_блокировку(арг[0])
        return 0

    if действие == "status":
        блок = set(прочитать_json(ПУТЬ_БЛОК, []))
        print()
        if not блок:
            print(ЗЕЛ + "  Заблокированных нет." + СБР)
            print()
            return 0
        print(КРАС + "  Заблокированы: " + ", ".join(sorted(блок)) + СБР)
        print(ЖЁЛ + "  Они убраны из конфига и не могут подключиться."
              + СБР)
        print(СЕР + "  Вернуть:  sora_traffic.py restore <имя>" + СБР)
        print()
        return 0

    if действие == "limit":
        if not арг or арг[0] in ("--list", "-l", "list"):
            показать_лимиты()
            return 0
        ник = арг[0]
        гб = float(арг[1]) if len(арг) > 1 else None
        предупредить = float(арг[2]) if len(арг) > 2 else None
        поставить_лимит(ник, гб, предупредить)
        return 0

    if действие == "unblock":
        if not арг:
            print()
            print(КРАС + "  Укажите имя: sora_traffic.py unblock ivan"
                  + СБР)
            print()
            return 1
        вернуть_блокировку(арг[0])
        return 0

    if действие == "reset":
        if not арг:
            print()
            print(КРАС + "  Укажите имя: sora_traffic.py reset ivan"
                  + СБР)
            print()
            return 1
        сбросить_счётчик(арг[0])
        return 0

    # сюда не дойдём: имя уже проверено выше
    print(КРАС + "  Неизвестная команда: %s" % действие + СБР)
    return 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nПрервано.")
        sys.exit(1)
