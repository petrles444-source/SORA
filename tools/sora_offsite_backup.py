#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Зашифрованная выгрузка ключей SORA на внешний FTP.

ЗАЧЕМ ЭТО НУЖНО

Ключи лежат только на сервере и на вашем компьютере. Оба места
уязвимы: диск может умереть, панель хостинга могут взломать, ноутбук
украдут. Когда ключ потерян, обслуживать людей больше нечем — новые
конфиги не выдать, старые не восстановить.

Единственная защита от этого — копия НА СЕРВЕРЕ, КОТОРОГО У ВАС НЕТ.
FTP-хранилище хостинга как раз такой чужой сервер.

ПОЧЕМУ ФАЙЛ ПЕРЕД ОТПРАВКОЙ ШИФРУЕТСЯ

FTP не шифрует ничего: и логин с паролем, и сам файл идут
открытым текстом. Значит:

  - перехват по дороге даёт ключи всем, кто стоит на пути;
  - администратор хранилища читает содержимое как обычный файл.

Внутри реестра лежит приватный ключ САМОГО сервера и приватные
ключи всех пользователей. Утечка такого файла означает, что
злоумышленник поднимает туннель под вашего человека и пропускает
его трафик через себя.

Поэтому наружу уходит только зашифрованный файл. В хранилище лежит
мешанина, которую не прочитать ни перехватчику, ни хранителю.

ЧЕМ ШИФРУЕМ

  Fernet из библиотеки cryptography — AES-128-CBC плюс HMAC-SHA256.
  Ключ получается из пароля через PBKDF2-HMAC-SHA256, 600 000
  итераций (норма OWASP на 2023 год; меньше — слабо, больше —
  заметно медленнее, а файлы всего несколько килобайт).

НИЧЕГО УСТАНАВЛИВАТЬ НЕ НУЖНО

  cryptography уже стоит — ею пользуется генератор ключей
  sora_keys.py. ftplib входит в стандартную поставку Python.

ОТКУДА ИДЁТ КОПИЯ

  С КОМПЬЮТЕРА, а не с сервера. Реестр всё равно лежит на вашем
  диске, и отправлять с сервера означало бы ставить на него ещё
  и FTP-клиент ради файла в два килобайта.

ГДЕ ЛЕЖИТ ПАРОЛЬ

Нигде в этом файле. По умолчанию спрашивается при каждом запуске.
Для автоматической выгрузки можно указать --файл-ключа, но тогда
файл ключа должен быть на другом носителе, чем бэкап: положив
рядом, вы отключаете шифрование, не заметив этого.

ЧТО КОПИРУЕТСЯ

  client/registry.json      главное: все ключи
  server/server.conf        приватные ключи всех клиентов и сервера
  client/*.conf             конфиги пользователей

ПОСЛЕ ОТПРАВКИ — ПРОВЕРКА

Файл скачивается обратно и расшифровывается, затем содержимое
сравнивается по SHA-256. Показывается только результат, сам файл
никуда не распаковывается на диск.

ЗАПУСК

  # разовый бэкап с паролем по запросу
  python tools/sora_offsite_backup.py --хост ftp.firstbyte.ru ...

  # проверить, что то, что лежит у них, читается и совпадает
  python tools/sora_offsite_backup.py --проверить ...

  # показать, что будет отправляться, ничего не отправляя
  python tools/sora_offsite_backup.py --проба ...
"""

from __future__ import annotations

import argparse
import base64
import ftplib
import getpass
import hashlib
import io
import json
import os
import secrets
import sys
import tarfile
import time
from pathlib import Path

from cryptography.fernet import Fernet, InvalidToken
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

КОРЕНЬ = Path(__file__).resolve().parent.parent

ИТЕРАЦИИ = 600_000
РАЗМЕР_СОЛИ = 16
ДЛИНА_КЛЮЧА = 44          # base64 от 32 байт — столько ждёт Fernet

# Расширение зашифрованного файла. Не .zip и не .tar.gz — чтобы
# никто не пытался открыть «просто так» и не удивлялся мусору.
РАСШИРЕНИЕ = ".soraenc"

# Что именно уходит наружу. Порядок имеет значение только для
# читаемости, на результат не влияет.
ЧТО_КОПИРОВАТЬ = [
    "client/registry.json",
    "server/server.conf",
]


def собрать(куда: Path) -> bytes:
    """Сложить ключевые файлы в один tar в памяти."""
    буфер = io.BytesIO()

    with tarfile.open(fileobj=буфер, mode="w") as архив:
        for относительный in ЧТО_КОПИРОВАТЬ:
            путь = КОРЕНЬ / относительный
            if not путь.exists():
                raise FileNotFoundError(
                    "нет файла %s — запускайте из пакета SORA" % относительный)
            архив.add(путь, arcname=относительный)

        каталог = КОРЕНЬ / "client"
        if каталог.is_dir():
            for конфиг in sorted(каталог.glob("*.conf")):
                архив.add(конфиг,
                          arcname="client/" + конфиг.name)

    return буфер.getvalue()


def получить_пароль(файл_ключа: str | None) -> bytes:
    """
    Взять пароль: из файла или с клавиатуры.

    Файла быть не должно рядом с бэкапом — иначе шифрование
    бессмысленно. Поэтому при включённом файле предупреждаем.
    """
    if файл_ключа:
        путь = Path(файл_ключа)
        if not путь.exists():
            raise FileNotFoundError("файла ключа нет: %s" % путь)
        # Права важны: файл с ключами не должен быть доступен другим
        try:
            режим = путь.stat().st_mode & 0o777
            if режим & 0o077:
                print("  ВНИМАНИЕ: на %s стоят права %o — файл читают все."
                      % (путь, режим))
                print("  Выполните:  chmod 600 %s" % путь)
                print("  Пока не исправите, продолжение небезопасно.")
                raise SystemExit(1)
        except (OSError, AttributeError):
            pass  # на Windows прав POSIX нет, проверим отдельно
        return путь.read_bytes()

    пароль = getpass.getpass("Пароль для шифрования бэкапа: ")
    if not пароль:
        print("  пустой пароль не годится")
        raise SystemExit(1)
    return пароль.encode("utf-8")


def вывести_ключ(пароль: bytes, соль: bytes) -> bytes:
    """
    Получить ключ Fernet из пароля.

    Fernet требует РОВНО 32 байта в url-safe base64. PBKDF2 с
    length=32 даёт эти 32 байта, кодируем — получаем 44 символа,
    ровно столько и ожидает Fernet.

    Дополнительной соли Fernet не добавляем: соль PBKDF2 уже есть и
    меняется при каждом запуске, поэтому два бэкапа с одним паролем
    всё равно получаются разными.
    """
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(),
        length=32,
        salt=соль,
        iterations=ИТЕРАЦИИ,
    )
    return base64.urlsafe_b64encode(kdf.derive(пароль))


def зашифровать(данные: bytes, пароль: bytes) -> bytes:
    """
    Зашифровать и вернуть самодостаточный файл.

    Формат: 16 байт соли | 44 байта ключа | шифротекст

    Соль лежит внутри файла намеренно: иначе для расшифровки
    понадобился бы ещё один файл, который тоже надо где-то хранить,
    и круг не замыкался бы.
    """
    соль = secrets.token_bytes(РАЗМЕР_СОЛИ)
    ключ = вывести_ключ(пароль, соль)
    шифротекст = Fernet(ключ).encrypt(данные)
    return соль + ключ + шифротекст


def расшифровать(блоб: bytes, пароль: bytes) -> bytes:
    """Обратная операция. Соль и формат берутся из самого файла."""
    начало = РАЗМЕР_СОЛИ
    если = начало + ДЛИНА_КЛЮЧА

    if len(блоб) < если:
        raise ValueError("файл слишком мал, это не наш бэкап")

    соль = блоб[:начало]
    ключ = блоб[начало:если]
    шифротекст = блоб[если:]

    # Ключ из файла не используем: он и так выводится из пароля и
    # соли. Сверяем их, чтобы не принять подменённый файл за свой.
    ожидаемый = вывести_ключ(пароль, соль)
    if ключ != ожидаемый:
        raise ValueError("неверный пароль либо файл повреждён")

    try:
        return Fernet(ключ).decrypt(шифротекст)
    except InvalidToken:
        raise ValueError("файл повреждён либо изменён") from None


def подключиться(хост: str, порт: int, пользователь: str, пароль: str,
                 пассивный: bool) -> ftplib.FTP:
    ftp = ftplib.FTP()
    ftp.connect(хост, порт, timeout=60)
    ftp.login(пользователь, пароль)
    if пассивный:
        ftp.set_pasv(True)
    else:
        # Активный режим почти всегда не нужен: он требует входящих
        # соединений к нам, что у клиента за NAT обычно невозможно.
        # Оставляем на случай, если FTP-сервер пассивный не умеет.
        ftp.set_pasv(False)
    return ftp


def положить(ftp: ftplib.FTP, имя: str, данные: bytes) -> None:
    ftp.storbinary("STOR " + имя, io.BytesIO(данные))


def забрать(ftp: ftplib.FTP, имя: str) -> bytes:
    куски = []
    ftp.retrbinary("RETR " + имя, куски.append)
    return b"".join(куски)


def имя_файла(каталог: str) -> str:
    """Имя файла на хранилище: каталог и дата."""
    дата = time.strftime("%Y%m%d")
    имя = f"sora-keys-{дата}{РАСШИРЕНИЕ}"
    if каталог:
        имя = f"{каталог.rstrip('/')}/{имя}"
    return имя


def главный() -> int:
    разбор = argparse.ArgumentParser(
        description="Зашифрованная выгрузка ключей SORA на FTP")
    разбор.add_argument("--хост", required=True)
    разбор.add_argument("--порт", type=int, default=21)
    разбор.add_argument("--пользователь", required=True)
    разбор.add_argument("--пароль", default=None,
                        help="пароль FTP; если не указан, спросит")
    разбор.add_argument("--каталог", default="",
                        help="папка на хранилище, например /backup")
    разбор.add_argument("--файл-ключа", default=None,
                        help="файл с паролем для автоматической выгрузки")
    разбор.add_argument("--активный-режим", action="store_true",
                        help="активный FTP вместо пассивного")
    разбор.add_argument("--проба", action="store_true",
                        help="только показать, ничего не отправляя")
    разбор.add_argument("--проверить", action="store_true",
                        help="скачать и расшифровать, сверить")
    арг = разбор.parse_args()

    print()
    print("═" * 62)
    print("  ВЫГРУЗКА КЛЮЧЕЙ SORA — ЗАШИФРОВАННАЯ")
    print("═" * 62)

    print()
    print("── что шифруем ──")
    try:
        данные = собрать(КОРЕНЬ)
    except FileNotFoundError as ошибка:
        print("  ", ошибка)
        return 1

    отпечаток = hashlib.sha256(данные).hexdigest()
    print(f"   исходных данных: {len(данные):,} байт")
    print(f"   SHA-256:         {отпечаток[:32]}…")
    with tarfile.open(fileobj=io.BytesIO(данные)) as архив:
        for член in архив.getmembers():
            print(f"     + {член.name}")
    print()

    if арг.проба:
        print("  Режим пробы: ничего не шифрую и не отправляю.")
        return 0

    print("── шифрование ──")
    пароль = получить_пароль(арг.файл_ключа)
    начало = time.time()
    блоб = зашифровать(данные, пароль)
    print(f"   {len(данные):,} байт -> {len(блоб):,} байт "
          f"за {time.time() - начало:.1f} с")
    print(f"   расшифровка для проверки: "
          f"{'совпало' if расшифровать(блоб, пароль) == данные else 'НЕ СОВПАЛО'}")
    print()

    имя = имя_файла(арг.каталог)

    print("── отправка ──")
    print(f"   сервер:  {арг.хост}:{арг.порт}")
    print(f"   каталог: {арг.каталог or '/'}")
    print(f"   файл:    {имя}")
    print()

    пароль_ftp = арг.пароль
    if не_задан(пароль_ftp):
        пароль_ftp = getpass.getpass("Пароль FTP: ")

    try:
        ftp = подключиться(арг.хост, арг.порт, арг.пользователь,
                            пароль_ftp, not арг.активный_режим)
    except ftplib.all_errors as ошибка:
        print(f"   НЕ ПОДКЛЮЧИЛСЯ: {ошибка}")
        print()
        print("   Проверьте адрес, порт и логин в панели хостинга.")
        return 1

    try:
        print(f"   приветствие сервера: {ftp.getwelcome()}")

        if арг.проверить:
            print()
            print("── проверка того, что лежит у них ──")
            полученный = забрать(ftp, имя)
            print(f"   скачано: {len(полученный):,} байт")
            расшифрованный = расшифровать(полученный, пароль)
            свпал = hashlib.sha256(расшифрованный).hexdigest() == отпечаток
            print(f"   SHA-256 совпадает: {'ДА' if свпал else 'НЕТ'}")
            if not свпал:
                print()
                print("   БЭКАП НЕ ПРИГОДЕН. Не считайте задачу выполненной.")
                return 1
            print("   бэкап читается и соответствует текущему состоянию.")
            return 0

        положить(ftp, имя, блоб)
        print(f"   отправлено: {len(блоб):,} байт")

        print()
        print("── сразу проверяем, что дошло ──")
        полученный = забрать(ftp, имя)
        print(f"   скачано обратно: {len(полученный):,} байт")
        расшифрованный = расшифровать(полученный, пароль)
        свпал = hashlib.sha256(расшифрованный).hexdigest() == отпечаток
        print(f"   SHA-256 совпадает: {'ДА' if свпал else 'НЕТ'}")
        if not свпал:
            print()
            print("   БЭКАП НЕ ПРИГОДЕН.")
            return 1
        print("   бэкап на месте, читается, соответствует оригиналу.")

        print()
        print("═" * 62)
        print("  ГОТОВО")
        print("═" * 62)
        print()
        print("  Теперь ключи есть в трёх местах:")
        print("    1. на вашем компьютере")
        print("    2. на сервере")
        print("    3. в зашифрованном виде на чужом хранилище")
        print()
        print("  ПАРОЛЬ ОТ БЭКАПА УНИЧТОЖЬТЕ, ЕСЛИ НЕ ПОМНИТЕ ЕГО:")
        print("  расшифровать без него будет невозможно.")
        return 0

    except ftplib.all_errors as ошибка:
        print(f"   ОШИБКА FTP: {ошибка}")
        return 1
    finally:
        try:
            ftp.quit()
        except Exception:
            pass


def не_задан(значение) -> bool:
    return значение is None or значение == ""


if __name__ == "__main__":
    sys.exit(главный())
