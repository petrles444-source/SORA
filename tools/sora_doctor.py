    # сообщения о причине. Здесь каталог создаём.
    каталог = os.path.dirname(os.path.abspath(куда))
    if not os.path.isdir(каталог):
        try:
            os.makedirs(каталог, exist_ok=True)
        except OSError as e:
            raise SystemExit("Не удалось создать каталог:\n  %s\n"
                             "  Причина: %s" % (каталог, e.strerror or e))
    try:
        with open(куда, "w", encoding="utf-8") as f:
            f.write(текст)
    except OSError as e:
        raise SystemExit("Не удалось записать отчёт:\n  %s\n"
                         "  Причина: %s" % (куда, e.strerror or e))
    return куда


