            нужно = ("PrivateKey", "Address", "ListenPort")
            нет = [k for k in нужно if k not in интер]
            if нет:
                с.проблема(г, "C1", "В [Interface] не хватает полей",
                           ", ".join(нет))
            else:
                с.ок(г, "C1", "Конфигурация сервера разбирается",
                     "секций: %d, порт %s"
                     % (len(секции), интер["ListenPort"]))

            if реестр and интер.get("PrivateKey") != \
                    реестр["meta"]["server_private_key"]:
                с.проблема(г, "C2", "Приватный ключ сервера в конфиге "
                              "не совпадает с реестром",
                           "конфиг собран из старой версии реестра",
                           "python sora_keys.py server --out server/server.conf")
            elif реестр:
                с.ок(г, "C2", "Ключ сервера совпадает с реестром")

            # параметры обфускации сервера
