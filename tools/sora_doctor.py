def группа_a(с: Сборщик, реестр):
    г = "A. КРИПТОГРАФИЯ"

    хор, опис = сверка()
    if хор:
        с.ок(г, "A1", "Реализация Curve25519 верна", опис)
    else:
        с.проблема(г, "A1", "Реализация Curve25519 неверна", опис,
                 "ключи получатся неправильными. Проверьте tools\\sora_keys.py")

    if not реестр:
        с.непроверено(г, "A2", "Формат ключей",
                      "реестра нет — сначала python sora_keys.py init")
        return

    # A2/A3: формат и зажим скаляра
    битых = []
    незажатых = []
    allkeys = [("сервер/приватный", реестр["meta"]["server_private_key"]),
               ("сервер/публичный", реестр["meta"]["server_public_key"])]
    for ник, п in реестр["peers"].items():
        allkeys += [(f"{ник}/приватный", п["private_key"]),
                    (f"{ник}/публичный", п["public_key"]),
                    (f"{ник}/psk", п["preshared_key"])]
    for где, значение in allkeys:
        try:
            сырой = base64.b64decode(значение, validate=True)
            if len(сырой) != 32:
                битых.append(f"{где}: {len(сырой)} байт вместо 32")
        except Exception as e:
            битых.append(f"{где}: {e}")
        # Ограничение скаляра применяется ТОЛЬКО к приватным ключам
        # Curve25519. PresharedKey — это не скаляр: это 32 случайных
        # байта, которые протокол подмешивает через HKDF, и никакого
        # требования к ним тут нет.
        # Первая версия проверки проверяла зажим и у PSK тоже — и
        # заблокировала 3 ключа, которые были совершенно исправны.
        # Это была ошибка проверки, а не ключей.
        if "приватный" in где:
            try:
                сырой = base64.b64decode(значение)
                if _зажать(сырой) != сырой:
                    незажатых.append(где)
            except Exception:
                pass

    if битых:
        с.проблема(г, "A2", "Ключи повреждены",
                   "; ".join(битых[:5]),
                   "перевыпустите ключи: sora_keys.py add заново")
    else:
        с.ок(г, "A2", "Формат ключей верный",
             "все %d ключей — валидный base64 по 32 байта" % len(allkeys))

    if незажатых:
        с.проблема(г, "A3", "Скаляры не зажаты по RFC 7748",
                   ", ".join(незажатых[:5]),
                   "такой ключ не подойдёт. Перевыпустите ключи.")
    else:
        с.ок(г, "A3", "Скаляры зажаты правильно",
             "проверено ограничение бит по RFC 7748")

    # A4: публичные выводятся из приватных
    несовп = []
    пары = [("сервер", реестр["meta"]["server_private_key"],
             реестр["meta"]["server_public_key"])]
    for ник, п in реестр["peers"].items():
        пары.append((ник, п["private_key"], п["public_key"]))
    for ник, priv, pub in пары:
        try:
            выведенный = _x25519(base64.b64decode(priv), БАЗА)
            if base64.b64encode(выведенный).decode() != pub:
                несовп.append(ник)
        except Exception:
            несовп.append(ник)
    if несовп:
        с.проблема(г, "A4", "Публичный ключ не соответствует приватному",
                   ", ".join(несовп[:5]),
                   "пара ключей рассогласована: туннель не поднимется")
    else:
        с.ок(г, "A4", "Пары ключей согласованы",
             "%d пар: публичный вычислен из приватного" % len(пары))

    # A5: уникальность
    значения = [v for _, v in allkeys]
    дубль = len(set(значения)) != len(значения)
    if дубль:
        с.проблема(г, "A5", "Ключи повторяются",
                   "одинаковые ключи у разных людей — одного отключит "
                   "вместе с другим")
    else:
        с.ок(г, "A5", "Все ключи различны",
             "%d ключей, повторов нет" % len(значения))


