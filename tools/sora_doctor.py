def группа_d(с: Сборщик, хост, порт):
    г = "D. СЕРВЕР"

    if not хост:
        с.непроверено(г, "D1", "Доступность сервера",
                      "адрес не задан: --сервер 1.2.3.4")
        с.непроверено(г, "D2", "Служба amnezia-awg-go",
                      "нужен SSH или локальный запуск")
        с.непроверено(г, "D3", "Потолок памяти VPN",
                      "нужен SSH или локальный запуск")
        с.непроверено(г, "D4", "Правила NAT", "нужен доступ к серверу")
        с.непроверено(г, "D5", "Пересылка пакетов", "нужен доступ к серверу")
        return

    # UDP проверить обычным сокетом нельзя — UDP без ответа не отличим
    # от закрытого порта. Проверяем разрешимость имени и TCP-закрытость
    # как косвенный признак, и честно говорим, что это не проверка UDP.
    try:
        инфо = socket.getaddrinfo(хост, None)
        с.ок(г, "D1", "Имя сервера разрешается",
             f"{хост} -> {инфо[0][4][0]}")
    except Exception as e:
        с.проблема(г, "D1", "Имя сервера не разрешается", str(e)[:80])
        return

    с.непроверено(г, "D2", "Служба amnezia-awg-go",
                  "проверяется только на самом сервере: "
                  "bash sora-health.sh")
    с.непроверено(г, "D3", "Потолок памяти VPN",
                  "проверяется на сервере: bash sora-health.sh")
    с.непроверено(г, "D4", "Правила NAT", "проверяется на сервере")
    с.непроверено(г, "D5", "Пересылка пакетов", "проверяется на сервере")

    # ── D6/D7. Занят ли порт VPN чем-то посторонним ───────────────
    #
    # ПОЧЕМУ ТАК СЛОЖНО. Первый вариант проверки просто подключался
    # по TCP к порту VPN и при успехе кричал: «порт занят другой
    # службой». На сервере 203.0.113.10 отвечает ЛЮБОЙ порт —
    # 39115, 39116, 39118, 51820 и заведомо свободный 59999.
    # Это делает антиddos-фильтр хостинг-провайдера: он принимает
    # соединение и молчит. То есть старая проверка показывала бы
    # «занят» при ЛЮБОМ состоянии сервера — и врала бы всегда.
    #
    # ПРАВИЛЬНЫЙ СПОСОБ — сравнение с заведомо свободным портом.
    # Если отвечают оба, зонд не несёт информации, и так и должен
    # быть помечен: не проверено. Если отвечает только порт VPN —
    # вот это уже настоящая находка.
    КОНТРОЛЬНЫЙ = 59999          # заведомо ничего не слушает

    def отвечает_ли(адрес, порт, пауза=4):
        try:
            with socket.create_connection((адрес, порт), timeout=пауза):
                return True
        except Exception:
            return False

    отв_впн = отвечает_ли(хост, порт)
    отв_контр = отвечает_ли(хост, КОНТРОЛЬНЫЙ)

    if отв_впн and отв_контр:
        с.непроверено(
            г, "D6", "Занят ли порт VPN — проверить нечем",
            "сервер отвечает и на %d, и на контрольном %d. Значит "
            "соединение завершает фильтр провайдера, а не служба "
            "на порту: зонд не различает эти случаи."
            % (порт, КОНТРОЛЬНЫЙ))
        с.совет(г, "D7", "Проверять порт надо на самом сервере",
                "ss -lunp | grep %d покажет, слушает ли кто-то "
                "настоящий UDP" % порт)
    elif отв_впн:
        с.проблема(
            г, "D6", "На порту VPN отвечает посторонняя служба",
            "%s:%d отвечает, а контрольный %d — нет. Значит на порту "
            "действительно кто-то слушает."
            % (хост, порт, КОНТРОЛЬНЫЙ),
            "проверьте на сервере: ss -lunp | grep %d. Либо смените "
            "порт в реестре и пересоберите конфиги." % порт)
    else:
        с.ок(г, "D6", "Порт VPN свободен",
             "%s:%d по TCP не отвечает — там нечего занимать"
             % (хост, порт))
        с.непроверено(
            г, "D7", "Работает ли сам VPN",
            "по TCP нельзя: AmneziaWG работает только по UDP, а UDP "
            "без ответа неотличим от закрытого порта. Проверяется "
            "подключением с ноутбука.")


