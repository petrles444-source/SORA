#  Отдельная реализация Curve25519 для самопроверки doctor'а.
#  Продублирована намеренно: генератор не должен зависеть от
#  doctor'а и наоборот. Сверка их выводов — тоже проверка.
# ══════════════════════════════════════════════════════════════
P255 = 2 ** 255 - 19
A24_ = 121665
БАЗА = b"\x09" + b"\x00" * 31


def _зажать(k: bytes) -> bytes:
    b = bytearray(k)
    b[0] &= 248
    b[31] &= 127
    b[31] |= 64
    return bytes(b)


def _x25519(k: bytes, u: bytes) -> bytes:
    скаляр = int.from_bytes(_зажать(k), "little")
    bb = bytearray(u)
    bb[31] &= 127
    x1 = int.from_bytes(bytes(bb), "little")
    x2, z2, x3, z3, св = 1, 0, x1, 1, 0
    for t in range(254, -1, -1):
        kt = (скаляр >> t) & 1
        if св ^ kt:
            x2, x3 = x3, x2
            z2, z3 = z3, z2
        св = kt
        A = (x2 + z2) % P255
        AA = A * A % P255
        B = (x2 - z2) % P255
        BB = B * B % P255
        E = (AA - BB) % P255
        C = (x3 + z3) % P255
        D = (x3 - z3) % P255
        DA = D * A % P255
        CB = C * B % P255
        x3 = pow(DA + CB, 2, P255)
        z3 = x1 * pow(DA - CB, 2, P255) % P255
        x2 = AA * BB % P255
        z2 = E * (AA + A24_ * E) % P255
    if св:
        x2, x3 = x3, x2
        z2, z3 = z3, z2
    return ((x2 * pow(z2, P255 - 2, P255)) % P255).to_bytes(32, "little")


def эталон_есть() -> bool:
    try:
        import cryptography  # noqa: F401
        return True
    except Exception:
        return False


def сверка(сколько: int = 50):
    """Сверяет реализацию с библиотекой. Возвращает (ок, описание)."""
    if not эталон_есть():
        for _ in range(20):
            a = _зажать(secrets.token_bytes(32))
            b = _зажать(secrets.token_bytes(32))
            if _x25519(a, _x25519(b, БАЗА)) != _x25519(b, _x25519(a, БАЗА)):
                return False, "обмен несимметричен"
        return True, "эталонной библиотеки нет, проверена самосогласованность"

    try:
        from cryptography.hazmat.primitives.asymmetric import x25519 as CX
    except Exception:
        return True, "эталон недоступен"

    for _ in range(сколько):
        priv = _зажать(secrets.token_bytes(32))
        peer = secrets.token_bytes(32)
        мой = _x25519(priv, peer)
        их = (CX.X25519PrivateKey.from_private_bytes(priv)
              .exchange(CX.X25519PublicKey.from_public_bytes(peer)))
        if мой != их:
            return False, "расхождение с эталоном"
    return True, "сверена с cryptography: %d обменов" % сколько


