def группа_f(с: Сборщик, реестр):
    г = "F. БЕЗОПАСНОСТЬ"

    # F1: права на реестр
    if not os.path.exists(ПУТЬ_РЕЕСТРА):
        с.непроверено(г, "F1", "Права на реестр", "реестра нет")
    else:
        if os.name != "nt":
            режим = os.stat(ПУТЬ_РЕЕСТРА).st_mode & 0o777
            if режим & 0o077:
                с.проблема(г, "F1", "Реестр читаем другими",
                           f"режим {режим:o}, приватные ключи видны всем",
                           "chmod 600 client/registry.json")
            else:
                с.ок(г, "F1", "Права на реестр закрыты", f"{режим:o}")
        else:
            с.совет(г, "F1", "Права на реестр",
                    "в Windows атрибуты не выставляются. Реестр лежит "
                    "в папке проекта — не отправляйте его в облако.")

    # F2: ключи не попали в git
    git_dir = os.path.join(КОРЕНЬ, ".git")
    гитигно = os.path.join(КОРЕНЬ, ".gitignore")
    if not os.path.exists(гитигно):
        с.совет(г, "F2", "Файл .gitignore",
                "его нет — при git add . реестр может уехать в историю")
    else:
        ignore = open(гитигно, encoding="utf-8", errors="replace").read()
        покрыт = ("client/" in ignore or "registry.json" in ignore
                  or "SORA" in ignore)
        if покрыт:
            с.ок(г, "F2", "Реестр защищён от попадания в git")
        else:
            с.проблема(г, "F2", "Реестр НЕ исключён из git",
                       "при git add . приватные ключи попадут в историю "
                       "навсегда",
                       "дописать в .gitignore:  client/\n  server/server.conf")

    # F3: ключи в конфиге сервера — ожидаем, но файл должен быть защищён
    if os.path.exists(ПУТЬ_СЕРВЕР_КОНФ):
        if os.name != "nt":
            режим = os.stat(ПУТЬ_СЕРВЕР_КОНФ).st_mode & 0o777
            (с.проблема(г, "F3", "Конфиг сервера читаем для всех",
                        f"{режим:o} — там приватные ключи всех клиентов")
             if режим & 0o077 else
             с.ок(г, "F3", "Конфиг сервера защищён", f"{режим:o}"))
        else:
            с.совет(г, "F3", "Конфиг сервера",
                    "содержит приватные ключи всех клиентов. "
                    "На сервере права должны быть 600.")

    # F4: приватные ключи не должны попасть в файлы, которые читают
    # посторонние. КОНФИГИ (.conf) сюда НЕ входят: клиентский конфиг
    # по определению содержит свой приватный ключ, без него он не
    # работает. Первая версия проверки ругалась на config-*.conf и
    # предлагала их удалить — это ложное срабатывание, оно учило бы
    # удалять рабочие конфиги. Искать надо там, куда ключ попадать
    # не должен: отчёты, журналы, переписка, исходники.
    УТЕЧИ_ИЩЕМ = (".md", ".html", ".log", ".txt", ".json", ".py", ".csv")
    РАЗРЕШЁННЫЕ = {"registry.json"}

    приватные = set()
    if реестр:
        приватные.add(реестр["meta"]["server_private_key"])
        for п in реестр.get("peers", {}).values():
            приватные.add(п["private_key"])
            приватные.add(п["preshared_key"])

    утечки = []
    проверено = 0
    if приватные:
        for корень, папки, файлы in os.walk(КОРЕНЬ):
            папки[:] = [d for d in папки
                        if d not in ("__pycache__", ".git", ".kadry",
                                     ".pytest_cache", "node_modules")]
            for имя in файлы:
                if not имя.endswith(УТЕЧИ_ИЩЕМ) or имя in РАЗРЕШЁННЫЕ:
                    continue
                полный = os.path.join(корень, имя)
                try:
                    if os.path.getsize(полный) > 4_000_000:
                        continue
                    текст = (open(полный, "rb").read()
                             .decode("utf-8", "replace"))
                except OSError:
                    continue
                проверено += 1
                for ключ in приватные:
                    if ключ in текст:
                        утечки.append(os.path.relpath(полный, КОРЕНЬ))
                        break

    if утечки:
        с.проблема(г, "F4", "Приватный ключ попал в файл, который "
                            "не должен его содержать",
                   ", ".join(sorted(set(утечки))[:6]),
                   "удалите эти файлы. Приватный ключ в скриншоте или "
                   "переписке — утечка, даже если файл стереть: его уже "
                   "кто-то видел. Тогда выпустите новый ключ: revoke, add.")
    else:
        с.ок(г, "F4", "Приватные ключи не попали в отчёты и журналы",
             ("%d ключей проверено по %d файлам "
              "(.conf исключены — им ключ положен по назначению)"
              % (len(приватные), проверено))
             if приватные else "реестра нет — искать нечего")

    # F5: в конфиге человека не должно быть ЧУЖИХ приватных ключей.
    # Это настоящая ошибка сборки: если у Иванова в конфиге приватный
    # ключ Маши — либо перепутаны файлы, либо доступ выдан не тому.
    подмена = []
    if реестр and os.path.isdir(ПАПКА_КЛИЕНТОВ):
        for fn in sorted(os.listdir(ПАПКА_КЛИЕНТОВ)):
            if not (fn.startswith("config-") and fn.endswith(".conf")):
                continue
            ник = fn[len("config-"):-len(".conf")]
            свой = реестр["peers"].get(ник, {}).get("private_key")
            try:
                текст = open(os.path.join(ПАПКА_КЛИЕНТОВ, fn),
                             encoding="utf-8").read()
            except OSError:
                continue
            чужие = []
            for другой, п in реестр["peers"].items():
                if другой != ник and п["private_key"] in текст:
                    чужие.append(другой)
            if реестр["meta"]["server_private_key"] in текст:
                чужие.append("СЕРВЕР")
            if чужие:
                подмена.append("%s: %s" % (ник, ", ".join(чужие)))
            elif свой and свой not in текст:
                подмена.append("%s: своего ключа в конфиге нет" % ник)

    if подмена:
        с.проблема(г, "F5", "В конфиге чужой приватный ключ",
                   "; ".join(подмена[:5]),
                   "пересоберите конфиги: sora_keys.py config <имя> "
                   "--out client/config-<имя>.conf")
    else:
        с.ок(г, "F5", "В каждом конфиге только свой ключ",
             "чужих приватных ключей не найдено"
             if реестр else "реестра нет — нечего сверять")


