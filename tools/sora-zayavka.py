# ─── Бот ────────────────────────────────────────────────────────────────────

class Бот:
    def __init__(self, токен: str):
        self.токен = токен
        self.смещение = 0
        self.ошибок_подряд = 0

    # ── отправка ──
    def послать(self, чат: int, текст: str, клавиатура: dict | None = None) -> bool:
        данные = {"chat_id": чат, "text": текст,
                  "parse_mode": "HTML", "disable_web_page_preview": True}
        if клавиатура:
            данные["reply_markup"] = клавиатура
        try:
            вызов(self.токен, "sendMessage", данные)
            return True
        except ОшибкаTelegram as e:
            в_журнал(f"НЕ ОТПРАВИЛОСЬ в чат {чат}: {e}")
            return False

    def подтвердить(self, id_нажатия: str) -> None:
        try:
            вызов(self.токен, "answerCallbackQuery",
                  {"callback_query_id": id_нажатия, "text": "Принято"})
        except ОшибкаTelegram:
            pass  # нажатие могло протухнуть — не критично

    # ── команды ──
    def обработать_сообщение(self, сообщение: dict) -> None:
        чат = сообщение.get("chat", {}).get("id")
        if not isinstance(чат, int):
            return
        текст = (сообщение.get("text") or "").strip()
        команда = тек.split()[0].lower().split("@")[0] if тек else ""

        имя = сообщение.get("from", {}).get("first_name") or "без имени"
        фамилия = сообщение.get("from", {}).get("last_name") or ""
        ник = сообщение.get("from", {}).get("username")
        полное = f"{имя} {фамилия}".strip()

        в_журнал(f"сообщение от {полное} ({ник or 'без ника'}): {текст[:120]}")

        if команда in ("/старт", "/start", "/начать", "/помощь"):
            self.послать(чат, ПРИВЕТ, клавиатура_старт())

        elif команда in ("/оформить", "/заявка", "/купить"):
            self.оформить(чат, полное, ник)

        elif команда in ("/статус", "/заявки", "/мои"):
            self.послать(чат, текст_статуса(чат), клавиатура_после())

        elif команда in ("/отмена", "/отозвать"):
            self.послать(чат,
                         "Чтобы отозвать заявку, напишите в поддержку "
                         "@mailsora_bot с номером заявки — её снимут вручную.")

        elif текст:
            self.послать(чат,
                         "Не понял команду. Вот что я умею:\n\n" + ПРИВЕТ,
                         клавиатура_старт())

    def обработать_кнопку(self, апдейт: dict) -> None:
        нажатие = апдейт.get("callback_query") or {}
        от_кого = нажатие.get("from", {})
        чат = нажатие.get("message", {}).get("chat", {}).get("id")
        команда = нажатие.get("data", "")
        id_нажатия = нажатие.get("id", "")
        if not isinstance(чат, int):
            return

        полное = ((от_кого.get("first_name") or "без имени") + " "
                  + (от_кого.get("last_name") or "")).strip()

        self.подтвердить(id_нажатия)

        if команда == "оформить":
            self.оформить(чат, полное, от_кого.get("username"))

        elif команда == "статус":
            self.послать(чат, текст_статуса(чат), клавиатура_после())

        elif команда == "подробно":
            self.послать(чат,
                         "🔧 Что входит за 500 ₽\n\n"
                         "• Подключаюсь к вашему серверу по SSH\n"
                         "• Ставлю VPN, открываю порты, настраиваю брандмауэр\n"
                         "• Выпускаю ключи под ваши устройства\n"
                         "• Настраиваю исключения — чтобы банк и ВК работали\n"
                         "• Проверяю на живом туннеле, а не «порт слушает»\n\n"
                         "Сервер покупаете вы сами, от 128 ₽ в месяц.\n"
                         "Одна сессия. 7 дней на вопросы по тому, что поставили.\n\n"
                         "Оформить — /оформить")

        elif команда == "отмена":
            self.послать(чат,
                         "Чтобы отозвать заявку, напишите в поддержку "
                         "@mailsora_bot с номером заявки.")

    def оформить(self, чат: int, имя: str, ник: str | None) -> None:
        номер, новая = новая_заявка(чат, имя, ник)
        заявка = None
        база = читать_заявки()
        заявка = база["заявки"].get(номер)

        if новая:
            в_журнал(f"ЗАЯВКА №{номер} от {имя} (@{ник or 'нет'})")
            self.послать(чат, ПОСЛЕ_ЗАЯВКИ.format(
                номер=номер,
                название=ТАРИФ["настройка"]["название"],
                цена=ТАРИФ["настройка"]["цена"]),
                клавиатура_после())
            # сообщение владельцу — туда же, где он смотрит /заявки
            if заявка:
                адрес = чат_владельца()
                if адрес:
                    self.послать(адрес,
                                 "🔔 НОВАЯ ЗАЯВКА С САЙТА\n\n"
                                 + текст_заявки(заявка) +
                                 "\n\nОткрыть: @mailsora_bot → /заявки")
                else:
                    в_журнал(f"ЗАЯВКА №{номер} создана, но чат владельца "
                             f"неизвестен — уведомление не отправлено")
        else:
            self.послать(чат,
                         f"У вас уже есть заявка №{номер}.\n\n"
                         + текст_статуса(чат),
                         клавиатура_после())

    # ── цикл ──
    def цикл(self) -> None:
        в_журнал("бот заявок запущен, жду сообщений")
        while True:
            try:
                обновления = вызов(
                    self.токен, "getUpdates",
                    {"offset": self.смещение, "timeout": 30,
                     "allowed_updates": ["message", "callback_query"]},
                    таймаут=70,
                ) or []
                self.ошибок_подряд = 0
            except ОшибкаTelegram as e:
                self.ошибок_подряд += 1
                в_журнал(f"ОПРОС НЕ УДАЛСЯ ({self.ошибок_подряд}/5): {e}")
                if self.ошибок_подряд >= 5:
                    в_журнал("пять ошибок подряд — перезапуск через 30 секунд")
                    time.sleep(30)
                    self.ошибок_подряд = 0
                else:
                    time.sleep(5)
                continue

            for апдейт in обновления:
                self.смещение = апдейт["update_id"] + 1
                try:
                    if "callback_query" in апдейт:
                        self.обработать_кнопку(апдейт)
                    elif "message" in апдейт:
                        self.обработать_сообщение(апдейт["message"])
                except Exception as e:
                    в_журнал(f"ОШИБКА ОБРАБОТКИ: {type(e).__name__}: {e}")


