# ─── Журнал ─────────────────────────────────────────────────────────────────

def в_журнал(текст: str) -> None:
    """Пишет в журнал. Ошибка записи не должна ронять работу бота."""
    строка = f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S}  {текст}"
    try:
        ЖУРНАЛ.parent.mkdir(parents=True, exist_ok=True)
        with open(ЖУРНАЛ, "a", encoding="utf-8") as f:
            f.write(строка + "\n")
    except OSError:
        pass


# ─── Файл заявок ────────────────────────────────────────────────────────────

def читать_заявки() -> dict:
    """Читает файл заявок. Битый файл не роняет бота: отдаём пустой."""
    if not ЗАЯВКИ.exists():
        return {"заявки": {}}
    try:
        данные = json.loads(ЗАЯВКИ.read_text(encoding="utf-8"))
        if not isinstance(данные, dict):
            raise ValueError("корень не объект")
        if not isinstance(данные.get("заявки"), dict):
            данные["заявки"] = {}
        return данные
    except (json.JSONDecodeError, ValueError, OSError) as e:
        в_журнал(f"ЧТЕНИЕ ЗАЯВОК НЕ УДАЛОСЬ: {e}. Беру пустой набор.")
        return {"заявки": {}}


def записать_заявки(база: dict) -> None:
    """Пишет атомарно: сначала во временный файл, потом переименование.

    Так читатель никогда не увидит наполовину записанный JSON.
    """
    tmp = ЗАЯВКИ.with_suffix(".json.tmp")
    текст = json.dumps(база, ensure_ascii=False, indent=2)
    tmp.write_text(текст, encoding="utf-8")
    os.replace(tmp, ЗАЯВКИ)


def с_блокировкой(fn):
    """Выполняет fn под блокировкой файла. sora-support пишет тем же файлом."""
    if fcntl is None:
        return fn()  # не Linux: работаем без блокировки
    ЗАЯВКИ.parent.mkdir(parents=True, exist_ok=True)
    деск = open(ЗАЯВКИ_ВРЕМ, "a+")
    try:
        fcntl.flock(деск, fcntl.LOCK_EX)
        return fn()
    finally:
        fcntl.flock(деск, fcntl.LOCK_UN)
        деск.close()


# ─── Обращение к Telegram ───────────────────────────────────────────────────

class ОшибкаTelegram(Exception):
    pass


def вызов(токен: str, метод: str, данные: dict | None = None,
          таймаут: int = 30) -> dict:
    """Один вызов API. Токен в исключение не попадает."""
    url = API.format(token=токен, method=метод)
    тело = json.dumps(данные).encode("utf-8") if данные else None
    req = urllib.request.Request(
        url, data=тело,
        headers={"Content-Type": "application/json"},
        method="POST" if данные else "GET",
    )
    try:
        with urllib.request.urlopen(req, timeout=таймаут) as r:
            ответ = json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        тело_ошибки = ""
        try:
            тело_ошибки = e.read().decode("utf-8")[:200]
        except Exception:
            pass
        raise ОшибкаTelegram(f"{метод}: HTTP {e.code}. {тело_ошибки}") from None
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        raise ОшибкаTelegram(f"{метод}: сеть недоступна ({type(e).__name__})") from None
    except json.JSONDecodeError:
        raise ОшибкаTelegram(f"{метод}: ответ не JSON") from None

    if not ответ.get("ok"):
        raise ОшибкаTelegram(f"{метод}: {ответ.get('description', 'без описания')}")
    return ответ.get("result")


# ─── Логика заявок ──────────────────────────────────────────────────────────

def новая_заявка(чат: int, имя: str, ник: str | None,
                 ключ_тарифа: str = "настройка") -> tuple[str, bool]:
    """Создаёт заявку. Возвращает (номер, создан_ли_новая).

    Повторный /оформить от того же человека не плодит дубликаты —
    находит его прошлую заявку и поднимает ей статус обратно.
    """
    тариф = ТАРИФ[ключ_тарифа]

    def работа() -> tuple[str, bool]:
        база = читать_заявки()
        заявки = база["заявки"]
        ид = str(чат)

        # уже есть заявка от этого человека?
        for номер, з in заявки.items():
            if з.get("клиент_id") == ид and з.get("тариф") == ключ_тарифа:
                if з.get("статус") in ("новая", "выдан"):
                    з["статус"] = "новая"
                    з["история"].append({
                        "куда": "новая (повторно)",
                        "время": datetime.datetime.now().strftime("%d.%m %H:%M"),
                    })
                    записать_заявки(база)
                    return номер, False
                return номер, False

        номер = 1
        while str(номер) in заявки:
            номер += 1
        теперь = datetime.datetime.now()
        заявки[str(номер)] = {
            # Номер лежит и в ключе, и в теле: sora-support читает по
            # ключу, а наш /статус показывает по полю. Без этого поля
            # список показывает «№?» и сортируется как попало.
            "номер": номер,
            "тариф": ключ_тарифа,
            "название": тариф["название"],
            "цена": тариф["цена"],
            "что": тариф["что"],
            "срок": тариф["срок"],
            "клиент_id": ид,
            "имя": имя,
            "ник": ник,
            "создана": теперь.strftime("%Y-%m-%d %H:%M"),
            "статус": "новая",
            "оплачено": None,
            "выдан_ключ": None,
            "источник": "сайт",
            "история": [{"куда": "новая",
                         "время": теперь.strftime("%d.%m %H:%M")}],
        }
        записать_заявки(база)
        return str(номер), True

    return с_блокировкой(работа)


def мои_заявки(чат: int) -> list[dict]:
    """Заявки конкретного человека, новые сверху."""
    база = читать_заявки()
    мои = [з for з in база["заявки"].values() if з.get("клиент_id") == str(чат)]
    return sorted(мои, key=lambda z: int(z.get("номер", 0) or 0), reverse=True)


# ─── Тексты ответов ─────────────────────────────────────────────────────────

def текст_статуса(чат: int) -> str:
    мои = мои_заявки(чат)
    if not мои:
        return НЕТ_ЗАЯВКИ
    строки = ["📋 Ваши заявки:", ""]
    for з in мои[:5]:
        строки.append(
            f"№{з.get('номер', '?')}  {з.get('название', '?')}, {з.get('цена', '?')} ₽"
            f"  [{з.get('статус', '?')}]"
            f"  от {з.get('создана', '?')}")
    if len(мои) > 5:
        строки.append(f"…и ещё {len(мои) - 5}")
    return "\n".join(строки)


def текст_заявки(з: dict) -> str:
    """Как заявка выглядит для владельца. Тот же формат, что в sora-support."""
    # Ник выносим отдельно: вложенные кавычки внутри f-string не
    # принимает Python 3.11, а на сервере именно он.
    ник = з.get("ник")
    хвост = f" (@{ник})" if ник else ""
    return (
        f"📋 Заявка №{з.get('номер', '?')}\n\n"
        f"Что: {з.get('название', '?')}\n"
        f"Цена: {з.get('цена', '?')} ₽, {з.get('срок', '')}\n"
        f"Что входит: {z.get('что', '')}\n\n"
        f"Кто: {з.get('имя', 'без имени')}{хвост}\n"
        f"Чат: {з.get('клиент_id', '?')}\n"
        f"Когда: {з.get('создана', '?')}\n"
        f"Статус: {з.get('статус', '?')}\n\n"
        f"Источник: {з.get('источник', 'бот')}"
    )


