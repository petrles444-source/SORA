#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Сборка публичной версии пакета SORA.

Что делает
    1. Копирует пакет во временный каталог.
    2. Удаляет настоящие ключи.
    3. Генерирует НОВЫЕ ключи — они не привязаны ни к какому серверу.
    4. Меняет адрес сервера на зарезервированный для документации.
    5. Убирает файлы, личные для владельца.
    6. Проверяет, что настоящих ключей в сборке нет.

ПОЧЕМУ НОВЫЕ КЛЮЧИ, А НЕ «ЗАМЕНИТЬ НА ЗАГЛУШКИ»

Ключи в примере должны быть настоящими по форме, иначе пример не
запустится: doctor потребует ровно 32 байта в base64, обфускация
должна совпадать с ключом. Заглушка вида «ВСТАВЬТЕ_КЛЮЧ» валидацию
не проходит, и человек, который повторит установку по документации,
вместо работающей программы получит ошибку.

Сгенерированные ключи — настоящие криптографические ключи, которые
не соответствуют ни одному серверу. Они бесполезны для атаки, потому
что сервера с ними не существует, и при этом проходят все проверки.

ПОЧЕМУ АДРЕС МЕНЯЕТСЯ НА 203.0.113.10

Подсеть 203.0.113.0/24 зарезервирована в RFC 5737 специально для
документации: использовать её в реальной сети запрещено. Ровно то,
что нужно для примера — адрес выглядит правдоподобно, но не указывает
на чей-либо сервер.

Публиковать рабочий адрес VPN-сервера в открытом репозитории незачем:
это приглашение для всех, кто ищет открытые AmneziaWG-эндпоинты.

ЗАПУСК
    python tools/build_publish.py

КОД ВОЗВРАТА
    0 — сборка готова и проверена
    1 — что-то не сошлось
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

КОРЕНЬ = Path(__file__).resolve().parent.parent

СТАРЫЙ_АДРЕС = "203.0.113.10"
НОВЫЙ_АДРЕС = "203.0.113.10"      # RFC 5737 TEST-NET-3, только для документации

# Личные файлы владельца. В публичный пакет они не входят.
ЛИЧНОЕ = [
    "ПИСЬМО-В-ПОДДЕРЖКУ-IPV6.md",
    "ПИСЬМО-2-В-ПОДДЕРЖКУ-IPV6.md",
]

# Файлы, которые не должны существовать в публичном репозитории
# НИ ПРИ КАКИХ ОБСТОЯТЕЛЬСТВАХ, даже если сейчас в них только
# подсказки. Человек, увидевший в репозитории файл с именем
# secrets.local.json, справедливо решит, что там лежат ключи.
ЗАПРЕЩЕНО_В_ПУБЛИКУ = [
    "client/secrets/secrets.local.json",
]

# .gitignore публичной копии. Отдельный от авторского: в авторском
# папка client/ игнорируется целиком, потому что там настоящие
# ключи. В публичной копии client/ содержит только сгенерированные
# демо-конфиги, и прятать их незачем — их и смотрят те, кто
# читает репозиторий.
#
# Важнее другое: человек клонирует репозиторий, запускает
# `sora_keys.py init` — и у него появляются СВОИ ключи. Именно их
# и надо прятать, а демо-примеры оставить на месте.
GITIGNORE_ПУБЛИЧНЫЙ = """# Ключи, которые появятся у того, кто клонировал репозиторий.
# Демо-примеры client/example-*.conf лежат рядом и не прячутся:
# они сгенерированы заново и соответствуют ни одному серверу.
client/registry.json
client/secrets/secrets.local.json
client/secrets/secrets.local.backup.json

# Отчёты и отладочные файлы
*.bak
*.testbak
docs/otchet-*.html
__pycache__/
*.pyc

# Резервные копии реестра (внутри содержат приватные ключи)
sora-keys-*.json
"""

# Git по умолчанию переписывает LF в CRLF при выдаче файлов на
# Windows-машине. Для bash-скриптов это смертельно: shebang с
# возвратом каретки не находит интерпретатор, и скрипт просто не
# запускается. Поэтому переносы строк фиксируются принудительно.
GITATTRIBUTES = """# Скрипты на bash ОБЯЗАНЫ иметь LF. Возврат каретки в конце
# shebang делает файл неисполняемым: bash ищет /bin/bash с
# хвостом-возвратом каретки, которого не существует.
* text=auto eol=lf

*.sh    text eol=lf
*.py    text eol=lf
*.md    text eol=lf
*.json  text eol=lf
*.conf  text eol=lf
*.html  text eol=lf
*.txt   text eol=lf

# Бинарники не трогать: перевод строк внутри ELF ломает файл.
server/bin/* binary
"""

РАСШИРЕНИЯ_ДЛЯ_ЗАМЕНЫ = {
    ".py", ".sh", ".md", ".json", ".html", ".htm", ".conf", ".txt", ".yml", ".yaml",
}


def копировать() -> Path:
    """Скопировать пакет во временный каталог, исключив рабочие папки.

    mkdtemp СОЗДАЁТ свой каталог, поэтому копируем не в него, а в
    подпапку SORA внутри. Иначе copytree падает с FileExistsError.
    """
    каталог = Path(tempfile.mkdtemp(prefix="sora-publish-"))
    сборка = каталог / "SORA"
    shutil.copytree(
        КОРЕНЬ, сборка,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".git",
                                      ".work", ".venv"))
    return сборка


def убрать_личное(сборка: Path) -> None:
    """Удалить документы и файлы, относящиеся только к владельцу."""
    for имя in ЛИЧНОЕ:
        путь = сборка / "docs" / имя
        if путь.exists():
            путь.unlink()
            print(f"  убран личный документ: docs/{имя}")

    for относительный in ЗАПРЕЩЕНО_В_ПУБЛИКУ:
        путь = сборка / относительный
        if путь.exists():
            путь.unlink()
            print(f"  убран файл с приватным именем: {относительный}")

    (сборка / ".gitignore").write_text(
        GITIGNORE_ПУБЛИЧНЫЙ, encoding="utf-8", newline="\n")
    (сборка / ".gitattributes").write_text(
        GITATTRIBUTES, encoding="utf-8", newline="\n")
    print("  записаны .gitignore и .gitattributes для публичной копии")


def новые_ключи(сборка: Path) -> None:
    """Стереть настоящие ключи и сгенерировать новые."""
    клиент = сборка / "client"
    клиент.mkdir(exist_ok=True)
    for старый in клиент.iterdir():
        if старый.is_file():
            старый.unlink()

    сервер_конфиг = сборка / "server" / "server.conf"
    if сервер_конфиг.exists():
        сервер_конфиг.unlink()

    генератор = сборка / "tools" / "sora_keys.py"

    шаги = [["init"]]
    for ник in ("alice", "bob"):
        шаги.append(["add", ник, "--note", "primer"])
    шаги.append(["server", "--out", str(сервер_конфиг)])
    for ник in ("alice", "bob"):
        шаги.append(["config", ник, "--out",
                     str(клиент / f"example-{ник}.conf")])

    for шаг in шаги:
        итог = subprocess.run(
            [sys.executable, str(генератор)] + шаг,
            capture_output=True, text=True, encoding="utf-8")
        if итог.returncode != 0:
            print("  генератор споткнулся на шаге:", шаг)
            print(итог.stdout or "")
            print(итог.stderr or "")
            raise SystemExit(1)

    print(f"  сгенерированы новые ключи, пользователи: alice, bob")


def заменить_адрес(сборка: Path) -> int:
    """Заменить рабочий адрес на зарезервированный для документации."""
    замен = 0

    for путь in sorted(сборка.rglob("*")):
        if not путь.is_file() or ".git" in путь.parts:
            continue
        if путь.suffix.lower() not in РАСШИРЕНИЯ_ДЛЯ_ЗАМЕНЫ:
            continue

        try:
            текст = путь.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue

        if СТАРЫЙ_АДРЕС not in текст:
            continue

        количество = текст.count(СТАРЫЙ_АДРЕС)
        текст = текст.replace(СТАРЫЙ_АДРЕС, НОВЫЙ_АДРЕС)

        # Пишем без BOM и только с LF: Windows-концы строк ломают
        # shebang у bash-скриптов.
        путь.write_text(текст, encoding="utf-8", newline="\n")
        замен += количество

    return замен


def проверить(сборка: Path) -> bool:
    """Проверить сборку сканером и поиском настоящих ключей."""
    print()
    print("  ── проверка синтаксиса и формата ──")
    сканер = сборка / "tools" / "find_cyrillic.py"
    итог = subprocess.run(
        [sys.executable, str(сканер), str(сборка), "--quiet"],
        capture_output=True, text=True, encoding="utf-8")
    print("   ", (итог.stdout or "").strip())
    if итог.returncode != 0:
        print("    СКАНЕР НАШЁ ПРОБЛЕМЫ — публиковать нельзя")
        return False

    print()
    print("  ── проверка настоящих ключей ──")
    проверка = сборка / "tools" / "publish_check.py"
    итог2 = subprocess.run(
        [sys.executable, str(проверка),
         str(КОРЕНЬ / "client" / "registry.json"), str(сборка)],
        capture_output=True, text=True, encoding="utf-8")
    print(итог2.stdout or "")
    if итог2.returncode != 0:
        print("    НАСТОЯЩИЕ КЛЮЧИ В СБОРКЕ — публиковать нельзя")
        return False

    return True


def финальная_проверка(сборка: Path) -> bool:
    """
    Последний рубеж. Проверяем то, что сканер ключей не видит:
    запрещённые имена файлов и рабочий адрес сервера.

    Сканер ищет значения ключей. Этот проход ищет то, чего в
    публичном репозитории быть не должно вообще, независимо от
    содержимого.
    """
    print()
    print("  ── финальная проверка ──")
    плохо = False

    for относительный in ЗАПРЕЩЕНО_В_ПУБЛИКУ:
        if (сборка / относительный).exists():
            print(f"    [!] в сборке есть {относительный}")
            плохо = True
    if not плохо:
        print("    запрещённых имён нет")

    # Рабочий адрес не должен остаться нигде, включая бинарники
    адрес_найден = False
    for путь in sorted(сборка.rglob("*")):
        if not путь.is_file():
            continue
        try:
            данные = путь.read_bytes()
        except OSError:
            continue
        if СТАРЫЙ_АДРЕС.encode("ascii") in данные:
            print(f"    [!] рабочий адрес найден в {путь.relative_to(сборка)}")
            адрес_найден = True
    if not адрес_найден:
        print(f"    рабочего адреса нет ни в одном файле (включая бинарники)")

    # В реестре сборки должны быть ровно два демо-пользователя
    реестр = сборка / "client" / "registry.json"
    if реестр.exists():
        данные = json.loads(реестр.read_text(encoding="utf-8"))
        пользователи = список_пользователей(данные)
        print(f"    пользователей в реестре: {пользователи}")
        if пользователи not in (["alice", "bob"], ["bob", "alice"]):
            print("    [!] в реестре не только демо-пользователи")
            плохо = True

    # Имена настоящих пользователей не должны встречаться в сборке.
    # Список берётся из НАСТОЯЩЕГО реестра, а не вписывается в код:
    # сам скрипт уезжает в публичный репозиторий, и зашитые в него
    # имена утекли бы вместе с ним.
    #
    # Сравнение по границам слова обязательно: короткое имя
    # пользователя без \b совпадёт внутри транслитерированного
    # русского слова в комментариях и даст ложную тревогу.
    настоящий = КОРЕНЬ / "client" / "registry.json"
    if настоящий.exists():
        имена = список_пользователей(
            json.loads(настоящий.read_text(encoding="utf-8")))
        for имя in имена:
            if len(имя) < 4:
                continue
            шаблон = re.compile(rf"\b{re.escape(имя)}\b")
            for путь in sorted(сборка.rglob("*")):
                if not путь.is_file():
                    continue
                try:
                    текст = путь.read_text(encoding="utf-8")
                except (UnicodeDecodeError, OSError):
                    continue
                if шаблон.search(текст):
                    print(f"    [!] имя пользователя {имя!r} найдено в "
                          f"{путь.relative_to(сборка)}")
                    плохо = True

    if плохо or адрес_найден:
        print("    ПУБЛИКОВАТЬ НЕЛЬЗЯ")
        return False
    return True


def список_пользователей(данные: dict) -> list[str]:
    """Достать имена пользователей из реестра любой формы."""
    пользователи = данные.get("users") or данные.get("peers") or данные.get("клиенты")
    if isinstance(пользователи, dict):
        return sorted(пользователи.keys())
    if isinstance(пользователи, list):
        имена = []
        for запись in пользователи:
            if isinstance(запись, dict):
                имена.append(запись.get("name") or запись.get("user") or "?")
            else:
                имена.append(str(запись))
        return sorted(имена)
    return []


def главный() -> int:
    print()
    print("═" * 66)
    print("  СБОРКА ПУБЛИЧНОЙ ВЕРСИИ SORA")
    print("═" * 66)
    print()

    сборка = копировать()
    print(f"  сборка: {сборка}")
    print()

    print("  ── очистка ──")
    убрать_личное(сборка)
    новые_ключи(сборка)

    print()
    print("  ── адрес сервера ──")
    сколько = заменить_адрес(сборка)
    print(f"    заменено вхождений: {сколько}")
    print(f"    {СТАРЫЙ_АДРЕС} -> {НОВЫЙ_АДРЕС}  (RFC 5737, для документации)")

    if not проверить(сборка):
        return 1

    if not финальная_проверка(сборка):
        return 1

    print()
    print("═" * 66)
    print("  ГОТОВО К ПУБЛИКАЦИИ")
    print("═" * 66)
    print(f"  папка: {сборка}")
    print()
    print("  Перед отправкой проверь ещё раз, глазами:")
    print(f"    client\\registry.json — новые ключи, не настоящие")
    print(f"    server\\server.conf   — два демо-пользователя")
    print(f"    client\\example-*.conf — примеры для Amnezia")
    print()
    print("  Настоящий пакет с вашими ключами остаётся здесь:")
    print(f"    {КОРЕНЬ}")
    return 0


if __name__ == "__main__":
    sys.exit(главный())
