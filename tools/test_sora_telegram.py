def main() -> int:
    print("=" * 70)
    print("ПРОВЕРКИ ИНСТРУМЕНТА ДОСТУПА К TELEGRAM")
    print("=" * 70)
    print("Сеть не используется, права root не нужны, сервер не затрагивается.")

    результаты = [
        ("проверка адреса", тест_проверка_адреса()),
        ("сборка правила", тест_сборка_правила()),
        ("удаление правила", тест_удаление_правила()),
        ("сгенерированный скрипт", тест_сгенерированный_скрипт()),
        ("unit-файл", тест_unit_файл()),
        ("распознавание ответа", тест_распознавание_ответа()),
    ]

    print("\n" + "=" * 70)
    всего = 0
    сбой = 0
    for имя, ок in результаты:
        всего += 1
        if not ок:
            сбой += 1
            print(f"  СБОЙ: {имя}")
    print(f"  разделов: {всего}, с ошибками: {сбой}")
    print("=" * 70)
    return 1 if сбой else 0


