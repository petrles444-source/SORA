#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Проверки инструмента доступа к Telegram API.

ЗАЧЕМ ЭТОТ ФАЙЛ

Каждый тест здесь отвечает на ошибку, которая либо уже была, либо
очень легко появляется. Инструмент работает на сервере, где он
переписывает правила iptables, — ошибка в нём стоит дорого, а
проверить его на живой машине нельзя без последствий. Поэтому всё
проверяемое вынесено в функции без сети и без прав root.

ЗАПУСК
    python tools/test_sora_telegram.py
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

КОМАНДА_ИСПОЛНЕНИЯ = []

модуль_spec = importlib.util.spec_from_file_location(
    "sora_telegram", Path(__file__).resolve().parent / "sora_telegram.py")
sora_telegram = importlib.util.module_from_spec(модуль_spec)
модуль_spec.loader.exec_module(sora_telegram)


def проверить(имя: str, условие: bool, подробность: str = "") -> bool:
    """Одна проверка. Ошибка печатается, выполнение не прерывается:
    полный отчёт полезнее первого же падения."""
    if условие:
        print(f"  [ок]   {имя}")
        return True
    print(f"  [сбой] {имя}")
    if подробность:
        for строка in подробность.splitlines():
            print(f"         {строка}")
    return False


# --------------------------------------------------------------------------
# 1. Адрес из резолвера попадает в команду iptables.
#
# Это внешний ввод. Значение вида «-j ACCEPT» или с пробелом,
# склеенное с другим аргументом, в iptables читается как флаг или
# разрывает команду. Проверяется отказ, а не «вроде разобралось».
# --------------------------------------------------------------------------

def тест_проверка_адреса() -> bool:
    print("\nПроверка адреса из резолвера")
    хорошо = True

    хорошо &= проверить(
        "нормальный IPv4 принимается",
        sora_telegram.днать("149.154.167.220") == "149.154.167.220")

    плохие = [
        ("пустая строка", ""),
        ("три части", "1.2.3"),
        ("пять частей", "1.2.3.4.5"),
        ("часть больше 255", "1.2.3.256"),
        ("не цифра", "1.2.3.4a"),
        ("начинается с минуса", "-1.2.3.4"),
        ("пустая часть", "1..3.4"),
        ("команда вперемешку", "1.2.3.4; reboot"),
        ("флаг iptables", "-j ACCEPT"),
        ("пробел внутри", "1.2.3.4 5.6.7.8"),
        ("перевод строки", "1.2.3.4\n-j ACCEPT"),
        ("кавычка", "1.2.3.4\" -j"),
        ("подстановка", "1.2.3.4$(id)"),
        ("памятка", "0.0.0.0/0"),
    ]
    for имя, значение in плохие:
        отвергнут = False
        try:
            sora_telegram.днать(значение)
        except ValueError:
            отвергнут = True
        хорошо &= проверить(f"отвергнут: {имя}", отвергнут,
                            f"  значение: {значение!r}")

    return хорошо


# --------------------------------------------------------------------------
# 2. Правило собирается из тех же частей, что и проверяется адрес.
# --------------------------------------------------------------------------

def тест_сборка_правила() -> bool:
    print("\nСборка правила iptables")
    хорошо = True
    правило = sora_telegram.правило_для("149.154.166.110", "149.154.167.220")

    хорошо &= проверить(
        "перенаправление с заблокированного на рабочий",
        правило == ("-p tcp -d 149.154.166.110 --dport 443 "
                    "-j DNAT --to-destination 149.154.167.220:443"),
        f"  получилось: {правило}")

    хорошо &= проверить(
        "адрес назначения попал в --to-destination",
        правило.endswith("--to-destination 149.154.167.220:443"))

    хорошо &= проверить(
        "адрес отправления попал в -d",
        "-d 149.154.166.110" in правило)

    хорошо &= проверить(
        "порт задан явно",
        "--dport 443" in правило)

    return хорошо


# --------------------------------------------------------------------------
# 3. Удаление правила.
#
# Здесь была ошибка, найденная на живом сервере: адрес брался из
# --to-destination и подставлялся в -d. Правило не совпадало,
# удаление не срабатывало, цикл крутился вечно. Тест фиксирует
# именно это: -d и --to-destination обязаны остаться РАЗНЫМИ.
# --------------------------------------------------------------------------

def тест_удаление_правила() -> bool:
    print("\nУдаление правила")
    хорошо = True

    строка = ("-A OUTPUT -d 149.154.166.110/32 -p tcp -m tcp --dport 443 "
              "-j DNAT --to-destination 149.154.167.220:443")
    аргументы = sora_telegram.аргументы_удаления(строка)

    хорошо &= проверить("аргументы разобраны", аргументы is not None)
    if аргументы is None:
        return False

    хорошо &= проверить(
        "префикс -A OUTPUT убран",
        аргументы[0] == "-d" and аргументы[1] == "149.154.166.110/32",
        f"  получилось: {аргументы[:3]}")

    хорошо &= проверить(
        "адрес ОТПРАВЛЕНИЯ на месте и он заблокированный",
        "-d" in аргументы and "149.154.166.110/32" in аргументы)

    хорошо &= проверить(
        "адрес НАЗНАЧЕНИЯ не подменён на адрес отправления",
        аргументы[аргументы.index("--to-destination") + 1]
        == "149.154.167.220:443",
        f"  получилось: {аргументы}")

    хорошо &= проверить(
        "оба адреса различны (иначе это была бы прошлая ошибка)",
        "149.154.166.110/32" in аргументы
        and "149.154.167.220:443" in аргументы)

    хорошо &= проверить(
        "правило не проходит само по себе как удаляющее",
        not аргументы or аргументы[0] not in ("-A", "-D"))

    for мусор in ["", "   ", "-A", "-A OUTPUT", "не правило вовсе",
                  "-P OUTPUT ACCEPT", "-D OUTPUT -j ACCEPT"]:
        хорошо &= проверить(
            f"мусор отвергнут: {мусор!r}",
            sora_telegram.аргументы_удаления(мусор) is None)

    return хорошо


# --------------------------------------------------------------------------
# 4. Порядок сохранения адресов в скрипте.
#
# Скрипт пишется на сервер и исполняется оттуда. BOM или CRLF в
# начале ломают shebang: bash ищет /bin/bash с хвостом-возвратом
# каретки, которого не существует. Молча, без сообщения.
# --------------------------------------------------------------------------

def тест_сгенерированный_скрипт() -> bool:
    print("\nСгенерированный bash-скрипт")
    хорошо = True
    скрипт = sora_telegram.сгенерировать_скрипт(
        "149.154.166.110", "149.154.167.220")

    хорошо &= проверить("не пустой", len(скрипт) > 200)

    хорошо &= проверить(
        "shebang на первой строке",
        скрипт.splitlines()[0] == "#!/bin/bash",
        f"  первая строка: {скрипт.splitlines()[0]!r}")

    хорошо &= проверить(
        "нет BOM",
        not скрипт.startswith("﻿"),
        f"  первые байты: {скрипт.encode('utf-8')[:6]!r}")

    хорошо &= проверить(
        "нет CRLF",
        "\r" not in скрипт,
        f"  позиции CR: {[i for i, c in enumerate(скрипт) if c == chr(13)][:5]}")

    хорошо &= проверить(
        "заканчивается переводом строки",
        скрипт.endswith("\n"))

    хорошо &= проверить(
        "заблокированный адрес в тексте",
        "149.154.166.110" in скрипт)

    хорошо &= проверить(
        "рабочий адрес в тексте",
        "149.154.167.220" in скрипт)

    хорошо &= проверить(
        "в правиле массива оба адреса",
        "RULE=(-p tcp -d 149.154.166.110 --dport 443 -j DNAT "
        "--to-destination 149.154.167.220:443)" in скрипт,
        f"  строка RULE: "
        f"{[s for s in скрипт.splitlines() if s.startswith('RULE=')]}")

    хорошо &= проверить(
        "идемпотентность заявлена (проверка -C перед -A)",
        "-C OUTPUT" in скрипт and "-A OUTPUT" in скрипт)

    хорошо &= проверить(
        "команда цитирована: ${RULE[@]}, а не $RULE",
        '"${RULE[@]}"' in скрипт,
        f"  строки с RULE: "
        f"{[s for s in скрипт.splitlines() if 'RULE[' in s]}")

    хорошо &= проверить(
        "нет табов (bash требует пробелы в отступах)",
        "\t" not in скрипт)

    # Подстановка адресов не должна ломать структуру массива.
    чужой = sora_telegram.сгенерировать_скрипт("10.0.0.1", "10.0.0.2")
    хорошо &= проверить(
        "другой адрес тоже даёт корректный массив",
        "RULE=(-p tcp -d 10.0.0.1 --dport 443 -j DNAT "
        "--to-destination 10.0.0.2:443)" in чужой)

    return хорошо


# --------------------------------------------------------------------------
# 5. unit-файл systemd.
# --------------------------------------------------------------------------

def тест_unit_файл() -> bool:
    print("\nUnit-файл systemd")
    хорошо = True
    unit = sora_telegram.сгенерировать_unit()

    хорошо &= проверить("секция [Unit]", "[Unit]" in unit)
    хорошо &= проверить("секция [Service]", "[Service]" in unit)
    хорошо &= проверить("секция [Install]", "[Install]" in unit)
    хорошо &= проверить(
        "ExecStart указывает на созданный скрипт",
        f"ExecStart={sora_telegram.SCRIPT_PATH}" in unit)
    хорошо &= проверить(
        "тип oneshot — правило ставится и всё",
        "Type=oneshot" in unit)
    хорошо &= проверить(
        "RemainAfterExit — сервис остаётся активным после запуска",
        "RemainAfterExit=yes" in unit)
    хорошо &= проверить(
        "включается в multi-user, то есть на загрузке",
        "WantedBy=multi-user.target" in unit)
    хорошо &= проверить(
        "нет CRLF",
        "\r" not in unit)
    хорошо &= проверить(
        "нет BOM",
        not unit.startswith("﻿"))

    return хорошо


# --------------------------------------------------------------------------
# 6. Отличить ответ Telegram от ответа кого угодно ещё.
#
# Ключевая мысль: «порт открыт» и «ответил Telegram» — не одно и то
# же, и «HTTP 200» тоже не обязательно Telegram. Признак один —
# JSON с полями ok и error_code.
# --------------------------------------------------------------------------

def тест_распознавание_ответа() -> bool:
    print("\nРаспознавание ответа Telegram")
    хорошо = True

    настоящий = json.dumps({"ok": False, "error_code": 401,
                            "description": "Unauthorized: invalid token "
                                           "specified"}).encode()
    хорошо &= проверить(
        "настоящий 401 от Telegram принят",
        sora_telegram._telegram_answered(401, настоящий, "HTTP 401", 0.15)[0])

    хорошо &= проверить(
        "настоящий 404 от Telegram принят",
        sora_telegram._telegram_answered(
            404,
            json.dumps({"ok": False, "error_code": 404,
                        "description": "Not Found"}).encode(),
            "HTTP 404", 0.10)[0])

    хорошо &= проверить(
        "HTML от промежуточного сервера отвергнут",
        not sora_telegram._telegram_answered(
            200, b"<html><body>Access denied</body></html>", "HTTP 200", 0.2)[0])

    хорошо &= проверить(
        "пустое тело отвергнуто",
        not sora_telegram._telegram_answered(200, b"", "HTTP 200", 0.2)[0])

    хорошо &= проверить(
        "JSON без полей Telegram отвергнут",
        not sora_telegram._telegram_answered(
            200, json.dumps({"status": "ok", "result": []}).encode(),
            "HTTP 200", 0.2)[0])

    хорошо &= проверить(
        "мусор вместо JSON отвергнут",
        not sora_telegram._telegram_answered(200, b"\x00\x01\x02\xff", "HTTP 200", 0.2)[0])

    хорошо &= проверить(
        "403 с текстом про страну не считается ответом Telegram",
        not sora_telegram._telegram_answered(
            403,
            json.dumps({"error": {"message": "Country, region, or "
                                               "territory not supported"}}).encode(),
            "HTTP 403", 0.3)[0])

    # Время попадает в текст: без него «за 12.01с» и «за 0.15с»
    # выглядели бы в отчёте одинаково.
    живой, текст = sora_telegram._telegram_answered(401, настоящий, "HTTP 401", 0.15)
    хорошо &= проверить("время отражено в тексте", "с," in текст, f"  текст: {текст}")
    хорошо &= проверить("код ответа отражен в тексте", "401" in текст)

    return хорошо


