def загрузить():
    """Грузит модуль. Точка входа не выполняется — есть `__main__`."""
    spec = importlib.util.spec_from_file_location("sora_keys_t", МОДУЛЬ)
    st = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(st)
    return st


