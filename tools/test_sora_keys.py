def тест_занятый_ник_отвергается(st):
    """Инструмент на занятый ник возвращает код 1, а не исключение.

    Первая версия теста ждала SystemExit и объявила исправное
    поведение ошибкой: инструмент честно отказал, вернул код, но
    исключение не бросил — а тест это не считал отказом.

    Теперь проверяется и код, и то, что никто не добавился.
    """
    import argparse
    снимок = json.load(open(st.ПУТЬ_РЕЕСТРА, encoding="utf-8"))
    before = снимок["peers"].get("ivan")
    before_peers = sorted(снимок["peers"])

    with тихо():
        код = st.команда_add(argparse.Namespace(имя="ivan", ip=None,
                                                note=""))
    после = json.load(open(st.ПУТЬ_РЕЕСТРА, encoding="utf-8"))
    не_изменился = (после["peers"].get("ivan") == before
                    and sorted(после["peers"]) == before_peers)
    if код == 1 and не_изменился:
        записать("add отказывает на занятом нике (код 1, реестр цел)",
                 True)
    else:
        записать("add отказывает на занятом нике", False,
                 "код %s, реестр изменился: %s"
                 % (код, not не_изменился))


