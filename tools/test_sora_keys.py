def тест_init_не_повторяет_ключ(st):
    """Две установки подряд дают разные серверные ключи.

    ВАЖНО. Тест стирает реестр и создаёт заново, поэтому обязан
    восстановить его — даже если упадёт. Первая версия этого не
    делала и стояла в середине прогона: она удаляла всех людей,
    и следующие тесты падали с KeyError. Теперь состояние
    сохраняется и возвращается в finally.
    """
    import argparse
    сохранённый = open(st.ПУТЬ_РЕЕСТРА, encoding="utf-8").read()
    арг = dict(server_ip="203.0.113.10", port=39117,
               network="10.77.0.0/24", server_address="10.77.0.1/24",
               dns="10.77.0.1", перезаписать=False)

    try:
        os.remove(st.ПУТЬ_РЕЕСТРА)
        with тихо():
            st.команда_init(argparse.Namespace(**арг))
        первый = json.load(open(st.ПУТЬ_РЕЕСТРА, encoding="utf-8"))

        os.remove(st.ПУТЬ_РЕЕСТРА)
        with тихо():
            st.команда_init(argparse.Namespace(**арг))
        второй = json.load(open(st.ПУТЬ_РЕЕСТРА, encoding="utf-8"))

        if первый["meta"]["server_private_key"] != \
                второй["meta"]["server_private_key"]:
            записать("повторный init выдаёт новый ключ", True)
        else:
            записать("повторный init выдаёт новый ключ", False,
                     "серверный ключ совпал — две установки получат "
                     "одинаковое значение")
    finally:
        with open(st.ПУТЬ_РЕЕСТРА, "w", encoding="utf-8") as f:
            f.write(сохранённый)


