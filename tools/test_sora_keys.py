@contextlib.contextmanager
def тихо():
    """Глушит вызовы инструмента.

    Тесты зовут add/init по десятку раз, и каждый печатает пять
    строк. Без заглушки вывод теста перестаёт быть читаемым и в
    нём теряется главное — строка с ошибкой.
    """
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
        yield buf

