def тест_битый_реестр(st):
    """Битый реестр должен говорить по-человечески, а не traceback'ом.

    Первая версия инструмента роняла json.JSONDecodeError прямо
    наружу. Пользователь видел «Expecting property name enclosed in
    double quotes» и стек вызовов — из этого ничего не следует и
    ничего не исправить. Теперь файл битый объясняется прямо.
    """
    хороший = open(st.ПУТЬ_РЕЕСТРА, encoding="utf-8").read()
    try:
        сломанные = [
            ("нечитаемый JSON", "{это не json"),
            ("обрезанный файл", '{"peers": {"ivan": {"private'),
            ("не тот формат", "[1, 2, 3]"),
            ("нет поля peers", '{"meta": {}}'),
        ]
        трассировки = []
        понятные = 0

        for имя, содержимое in сломанные:
            with open(st.ПУТЬ_РЕЕСТРА, "w", encoding="utf-8") as f:
                f.write(содержимое)
            try:
                st.прочитать()
                # не упало — тоже приемлемо, если вернёт пустое
                понятные += 1
            except SystemExit as e:
                текст = str(e)
                if "Traceback" in текст:
                    трассировки.append(имя)
                elif len(текст) > 20:
                    понятные += 1
                else:
                    трассировки.append(имя + " (короткое сообщение)")
            except Exception as e:
                трассировки.append("%s: %s" % (имя, type(e).__name__))

        if not трассировки:
            записать("битый реестр объясняется, а не роняет (%d случая)"
                     % len(сломанные), True)
        else:
            записать("битый реестр объясняется, а не роняет", False,
                     "; ".join(трассировки[:3]))
    finally:
        with open(st.ПУТЬ_РЕЕСТРА, "w", encoding="utf-8") as f:
            f.write(хороший)


def тест_диапазоны_обфускации(st):
    """Каждый параметр обфускации должен быть в своём типе.

    НАЙДЕНО НА ЖИВОМ СЕРВЕРЕ 15.10.2026.

    S1 и S2 генерировались как randbelow(2**32), то есть
    0..4294967295. Настоящий awg такие значения отвергает:
    в amneziawg-tools/src/config.c S1/S2/Jc/Jmin/Jmax идут
    через parse_uint16, а он проверяет `ret > UINT16_MAX`
    и вызывает exit(1). Сервер падал ровно на этом:

        Unable to parse S1: `3295741239'

    Почему 38 тестов этого не видели: они проверяли, что поле
    ЕСТЬ и что оно целое. Но «поле есть» и «настоящая программа
    такое значение примет» — разные вещи. Проверяем диапазон.

    Разделение взято из исходника amneziawg-tools, а не из
    головы: parse_uint16 — это uint16, u32_range_from_string —
    это uint32.
    """
    UINT16_MAX = 65535
    UINT32_MAX = 2 ** 32 - 1

    через_uint16 = ("Jc", "Jmin", "Jmax", "S1", "S2")
    через_uint32 = ("H1", "H2", "H3", "H4")

    ошибки = []
    for _ in range(60):
        об = st.новый_обфускация()

        for имя in через_uint16:
            v = об[имя]
            if not isinstance(v, int):
                ошибки.append("%s = %r, а нужен целый" % (имя, v))
            elif v < 0 or v > UINT16_MAX:
                ошибки.append("%s = %d, вне uint16 (0..%d)"
                              % (имя, v, UINT16_MAX))

        for имя in через_uint32:
            v = об[имя]
            if not isinstance(v, int):
                ошибки.append("%s = %r, а нужен целый" % (имя, v))
            elif v < 0 or v > UINT32_MAX:
                ошибки.append("%s = %d, вне uint32" % (имя, v))

    if ошибки:
        записать("диапазоны обфускации принимает awg (60 прогонов)",
                 False, "; ".join(sorted(set(ошибки))[:4]))
    else:
        записать("диапазоны обфускации принимает awg (60 прогонов)",
                 True)

    об = st.новый_обфускация()
    if об["S1"] <= UINT16_MAX and об["S2"] <= UINT16_MAX:
        записать("S1 и S2 помещаются в uint16", True)
    else:
        записать("S1 и S2 помещаются в uint16", False,
                 "S1=%d S2=%d" % (об["S1"], об["S2"]))


def тест_конфиги_без_cr(st):
    """Конфиги должны писаться с LF, а не с CRLF.

    НАЙДЕНО НА ЖИВОМ СЕРВЕРЕ 15.10.2026.

    Файлы писались обычным текстовым режимом: open(путь, "w").
    На Windows это означает \r\n. Конфиг уезжал на Linux уже с
    лишними CR внутри строк:

        Address = 10.77.0.1/24^M$

    Для Windows такой файл читается нормально, поэтому на своей
    машине всё выглядело исправным. На Linux лишний \r попадает
    в значение поля, и разбор ломается.

    Отсюда правило: конфиг для сервера пишется из Windows, но
    переводы строк в нём должны быть LF.
    """
    import argparse
    import shutil as _sh

    база4 = tempfile.mkdtemp(prefix="sora_lf_")
    цель = os.path.join(база4, "SORA")
    os.makedirs(os.path.join(цель, "client"))
    os.makedirs(os.path.join(цель, "server"))

    spec = importlib.util.spec_from_file_location("k4", МОДУЛЬ)
    st4 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(st4)
    st4.КОРЕНЬ = цель
    st4.ПУТЬ_РЕЕСТРА = os.path.join(цель, "client", "registry.json")
    st4.ПУТЬ_СЕРВЕР = os.path.join(цель, "server", "server.conf")

    серв = os.path.join(база4, "server.conf")
    кли = os.path.join(база4, "alice.conf")

    try:
        with тихо():
            st4.команда_init(argparse.Namespace(
                server_ip="203.0.113.10", port=39117,
                network="10.77.0.0/24", server_address="10.77.0.1/24",
                dns="10.77.0.1", перезаписать=False))
            st4.команда_add(argparse.Namespace(имя="alice", ip=None,
                                               note=""))
            st4.команда_server(argparse.Namespace(out=серв))
            st4.команда_config(argparse.Namespace(имя="alice", out=кли))

        плохие = []
        for имя, путь in (("server.conf", серв), ("alice.conf", кли)):
            if not os.path.isfile(путь):
                плохие.append("%s не создан" % имя)
                continue
            сырые = open(путь, "rb").read()
            if b"\r" in сырые:
                n = сырые.count(b"\r")
                плохие.append("%s: %d символов CR" % (имя, n))
            elif not сырые:
                плохие.append("%s пуст" % имя)

        if плохие:
            записать("конфиги пишутся с LF, без CR", False,
                     "; ".join(плохие))
        else:
            записать("конфиги пишутся с LF, без CR", True)
    finally:
        _sh.rmtree(база4, ignore_errors=True)


def тест_коды_возврата(st, копия):
    """Проверяем коды через отдельный процесс на изолированной копии."""
    база = tempfile.mkdtemp(prefix="sora_keys_cli_")
    цель = os.path.join(база, "SORA")
    # ИСКЛЮЧАЕМ client/ и server/server.conf.
    #
    # НАЙДЕНО 15.10.2026. Тест копировал ВСЁ дерево пакета и
    # рассчитывал, что реестра в нём нет. Пока каталог client/
    # был пуст — работало. Стоило появиться настоящему реестру
