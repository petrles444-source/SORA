def окружение():
    """Создаёт временный SORA-копию и перенастраивает модуль на неё."""
    база = tempfile.mkdtemp(prefix="sora_keys_t_")
    копия = os.path.join(база, "SORA")
    os.makedirs(os.path.join(копия, "client"))
    os.makedirs(os.path.join(копия, "server"))
    shutil.copy2(МОДУЛЬ, os.path.join(копия, "tools_keys.py"))

    st = загрузить()
    st.КОРЕНЬ = копия
    st.ПУТЬ_РЕЕСТРА = os.path.join(копия, "client", "registry.json")
    st.ПУТЬ_СЕРВЕР = os.path.join(копия, "server", "server.conf")
    return st, копия, база


