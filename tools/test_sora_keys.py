def запустить(арг, ожидаем_код=None):
    """Запускает sora_keys.py как отдельный процесс."""
    p = subprocess.run([sys.executable, МОДУЛЬ] + арг,
                       capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    if ожидаем_код is not None and p.returncode != ожидаем_код:
        return p, False
    return p, True


