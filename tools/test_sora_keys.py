def тест_реестр_переживает_перезапуск(st, копия):
    """Отдельный процесс должен увидеть тот же реестр."""
    cmd = [sys.executable, "-c", (
        "import importlib.util,sys;"
        "spec=importlib.util.spec_from_file_location('k',r'%s');"
        "m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);"
        "m.КОРЕНЬ=r'%s';m.ПУТЬ_РЕЕСТРА=r'%s';m.ПУТЬ_СЕРВЕР=r'%s';"
        "r=m.прочитать();"
        "print(sorted(r['peers'].keys()))" % (МОДУЛЬ, копия,
                                              st.ПУТЬ_РЕЕСТРА,
                                              st.ПУТЬ_СЕРВЕР))]
    p = subprocess.run(cmd, capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    ожидали = ["'ivan'", "'masha'", "'petr'", "'olga'"]
    нашли = [имя for имя in ожидали if имя in (p.stdout or "")]
    if len(нашли) == 4:
        записать("реестр переживает перезапуск процесса", True)
    else:
        записать("реестр переживает перезапуск процесса", False,
                 "нашли %d из 4; вывод: %s"
                 % (len(нашли), (p.stdout or p.stderr).strip()[:60]))


