    # же `init` находит его и возвращает 1 вместо ожидаемого 0.
    #
    # То есть тест проходил не потому, что был написан верно,
    # а потому что каталог случайно пуст. Это хуже падения:
    # падение честнее.
    shutil.copytree(КОРЕНЬ, цель,
                    ignore=shutil.ignore_patterns("__pycache__", ".git",
                                                  "client"))
    скрипт = os.path.join(цель, "tools", "sora_keys.py")

    ожидания = [
        # на чистой копии init обязан СОЗДАТЬ реестр и вернуть 0
        (["init"], 0),
        (["audit"], None),
        (["list"], None),
        (["server"], None),
        # второй init на существующем реестре обязан отказать
        (["init"], 1),
        # неизвестный ник и отозванный — отказ с кодом 1
        (["config", "nesushchestvuyushchiy"], 1),
    ]
    ок = True
    подробно = []
    for арг, код in ожидания:
        p = subprocess.run([sys.executable, скрипт] + арг,
                           capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
        if код is None:
            # не знаем код, но не должно быть traceback
            if "Traceback" in p.stdout + p.stderr:
                ок = False
                подробно.append("%s: traceback" % арг[0])
        else:
            if p.returncode != код:
                ок = False
                подробно.append("%s: код %s, ждали %s"
                                % (арг[0], p.returncode, код))

    if ок:
        записать("коды возврата верны, traceback нет", True)
    else:
        записать("коды возврата верны, traceback нет", False,
                 "; ".join(подробно))

    shutil.rmtree(база, ignore_errors=True)


