#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Поиск СМЕШАННОГО АЛФАВИТА и сбоев формата в скриптах SORA.

ЗАЧЕМ ЭТОТ ИНСТРУМЕНТ
=====================

В проекте два слоя текста, и оба разрешены:

  КОММЕНТАРИИ и ВЫВОД — по-русски. Это осознанно, так читается лучше.
  ИМЕНА ПЕРЕМЕННЫХ в bash — только латиница. Это НЕ stylistic choice:
  с кириллицей в имени переменной bash даёт «bad substitution».

Значит, «есть кириллица в .sh» — не диагноз. Половина проекта на русском.

Настоящая поломка выглядит иначе. Это СЛОВО, В КОТОРОМ СМЕШАЛИСЬ
КИРИЛЛИЦА И ЛАТИНИЦА:

    note "Sluzhbu perezapusk, konfig perezapishetsya sverху."  # sora-scan: skip
                                                      ^^^^^^
    blue "Ili sohranit fайл v /tmp i peredat ego, skript podхватит сам."  # sora-scan: skip
                            ^^^^                 ^^^^^^^^^

Почему это хуже всего остального:

  1. `bash -n` ЭТО ПРОПУСКАЕТ. Синтаксис корректен.
  2. Интерпретатор ЭТО ПРОПУСКАЕТ. Строка исполняется.
  3. Пользователь видит «sverху» — слово, которого нет ни в одном  # sora-scan: skip
     словаре, и не понимает, что это вообще такое.

Чисто кириллическое слово («работает») — нормально.
Чисто латинское слово («konfig») — нормально.
Смешанное «sverху» — это опечатка, и её надо ловить автоматически.  # sora-scan: skip

ЧТО ЕЩЁ ПРОВЕРЯЕТСЯ
  - BOM        — в bash это часть shebang
  - CRLF       — shebang становится '#!/bin/bash\\r' и не работает
  - кириллица в ИМЕНАХ переменных bash (жёсткое требование)
  - табы в начале строки в .sh (bash требует пробелы)

ЧТО НЕ ПРОВЕРЯЕТСЯ И ПОЧЕМУ
  - кириллица в идентификаторах Python: работает (PEP 3131) и
    выбрана в проекте осознанно (`записать`, `строки`, `ИТОГИ`).
  - чистая кириллица в строках и комментариях: это норма проекта.

ЗАПУСК
  python tools/find_cyrillic.py server tools
  python tools/find_cyrillic.py            # весь пакет
  python tools/find_cyrillic.py --quiet    # только итог
  python tools/find_cyrillic.py --json

КОД ВОЗВРАТА
  0 — чисто
  1 — найдены проблемы
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

КИРИЛЛИЦА = re.compile("[Ѐ-ӿ]")
ЛАТИНИЦА = re.compile("[A-Za-z]")

# Слово из букв и апострофов/дефисов — чтобы поймать «sverху», но  # sora-scan: skip
# не срезать куски вроде «sora-health.sh» или «${SORADIR}/tracker».
СЛОВО = re.compile("[0-9A-Za-zЀ-ӿ]+")  # sora-scan: skip

# Перед поиском смешанных слов убираем то, что объясняет смешение
# законным образом. Иначе будут сотни ложных срабатываний:
#
#   "%sНе могу прочитать"  — %s это цвет, «Не» чистая кириллица,
#                            но без пробела они склеиваются в «sНе»  # sora-scan: skip
#   "\nПрервано"           — \n это перевод строки, склеивается в «nПрервано»  # sora-scan: skip
#   "%d проверок"          — %d это число
#
# Всё это не опечатки, а нормальный код. Убираем заранее.
ФОРМАТ_СПЕЦИФИКАЦИЯ = re.compile(
    r"%[-+ #0]*[0-9*]*(?:\.[0-9*]+)?[hlL]?[diouxXeEfFgGcrsa%]")
ЭКРАН_ПОСЛЕ_СЛЕША = re.compile(r"\\[nrtvabf0\\'\"$`\s]")


def убрать_код(строка: str) -> str:
    """
    Убрать спецпоследовательности, из-за которых смешение выглядит
    ложным: форматы (%s, %d) и экранированные символы (\n, \t).

    Заменяем их пробелами, чтобы соседние слова не склеивались.
    """
    строка = ФОРМАТ_СПЕЦИФИКАЦИЯ.sub(" ", строка)
    строка = ЭКРАН_ПОСЛЕ_СЛЕША.sub(" ", строка)
    return строка

# Имя переменной bash: только латиница. Ключевые слова bash и служебные
# имена исключены — они не наши.
КЛЮЧЕВЫЕ = {
    "if", "then", "else", "elif", "fi", "for", "while", "until", "do",
    "done", "case", "esac", "in", "select", "function", "time", "coproc",
    "break", "continue", "return", "exit", "local", "export", "readonly",
    "declare", "typeset", "unset", "shift", "source", "eval", "exec",
    "trap", "set", "getopts", "test", "echo", "printf", "read", "mapfile",
    "BASH_SOURCE", "BASH_VERSION", "PIPESTATUS", "FUNCNAME", "LINENO",
    "RANDOM", "SECONDS", "SECONDS", "PWD", "OLDPWD", "HOME", "PATH",
    "IFS", "HOSTNAME", "USER", "UID", "EUID", "PPID", "SHELL", "TMPDIR",
    "RANDOM", "OPTARG", "OPTIND", "OSTYPE", "MACHTYPE", "HOSTTYPE",
}

РАСШИРЕНИЯ = {".sh", ".py"}
ИМЯ_СКРИПТА = re.compile(r"^nfp-plugin-")


def это_bash(путь: Path) -> bool:
    return путь.suffix.lower() == ".sh" or bool(ИМЯ_СКРИПТА.match(путь.name))


def убрать_комментарий(строка: str) -> str:
    """
    Убрать комментарий, не потеряв '#' внутри строк.
    Следим за открытой кавычкой — этого достаточно.
    """
    внутри: str | None = None
    экранирован = False

    for индекс, символ in enumerate(строка):
        if экранирован:
            экранирован = False
            continue
        if символ == "\\":
            экранирован = True
            continue
        if внутри is not None:
            if символ == внутри:
                внутри = None
            continue
        if символ in "'\"":
            внутри = символ
            continue
        if символ == "#":
            return строка[:индекс]

    return строка


# Строка с этой пометкой не проверяется. Нужна в двух случаях:
#
#   1. В ЭТОМ ФАЙЛЕ — примеры «sverху» в описании и классы символов  # sora-scan: skip
#      вида [A-Za-zЀ-ӿ]. Сканер не может отличить «пример опечатки»  # sora-scan: skip
#      от «настоящей опечатки», не заглянув в себя.
#   2. В РЕГУЛЯРНЫХ ВЫРАЖЕНИЯХ, где смешение ЗАМЫСЛЕНО:
#      r"^[А-ЯA-Z]" — это «буква-заглавная, хоть кириллица,  # sora-scan: skip
#      хоть латиница», и так и должно быть.
ПРОПУСК = "# sora-scan: skip"


def найти_смешанные(текст: str) -> list[dict]:
    """
    Слова, где смешались кириллица и латиница.
    Это и есть опечатки вида «sverху».  # sora-scan: skip
    """
    проблемы: list[dict] = []
    виденные: set[tuple[int, str]] = set()

    for номер, строка in enumerate(текст.split("\n"), 1):
        if ПРОПУСК in строка:
            continue
        код = убрать_код(убрать_комментарий(строка))

        for совпадение in СЛОВО.finditer(код):
            слово = совпадение.group(0)

            # игнорируем то, что встречается дважды подряд — это
            # повтор одного и того же слова в одном совпадении
            есть_кириллица = bool(КИРИЛЛИЦА.search(слово))
            есть_латиница = bool(ЛАТИНИЦА.search(слово))

            if not (есть_кириллица and есть_латиница):
                continue

            ключ = (номер, слово)
            if ключ in виденные:
                continue
            виденные.add(ключ)

            позиция = совпадение.start()
            начало = max(0, позиция - 20)
            конец = min(len(код), позиция + len(слово) + 20)
            контекст = код[начало:конец].strip()

            проблемы.append({
                "вид": "СМЕШАННЫЙ-АЛФАВИТ",
                "строка": номер,
                "слово": слово,
                "текст": f"«{слово}»   в: …{контекст}…",
            })

    return проблемы


def найти_кириллицу_в_именах(текст: str) -> list[dict]:
    """
    Кириллица в ИМЕНАХ переменных и функций — жёсткий отказ bash.

    Ловим только присваивание `имя=` и объявление функции `имя()`.
    Всё остальное (строки, комментарии) — не наш случай.
    """
    присваивание = re.compile(r"^\s*([A-Za-zЀ-ӿ_][A-Za-zЀ-ӿ_0-9]*)=")  # sora-scan: skip
    функция = re.compile(r"^\s*([A-Za-zЀ-ӿ_][A-Za-zЀ-ӿ_0-9]*)\s*\(\s*\)")  # sora-scan: skip

    проблемы: list[dict] = []
    виденные: set[tuple[int, str]] = set()

    for номер, строка in enumerate(текст.split("\n"), 1):
        код = убрать_комментарий(строка)
        if not код.strip():
            continue

        имя = None
        for образец in (присваивание, функция):
            совпадение = образец.match(код)
            if совпадение and КИРИЛЛИЦА.search(совпадение.group(1)):
                имя = совпадение.group(1)
                break

        if имя is None:
            continue

        ключ = (номер, имя)
        if ключ in виденные:
            continue
        виденные.add(ключ)

        проблемы.append({
            "вид": "КИРИЛЛИЦА-В-ИМЕНИ",
            "строка": номер,
            "слово": имя,
            "текст": f"переменная «{имя}» — bash даст bad substitution",
        })

    return проблемы


def проверить_формат(данные: bytes) -> list[dict]:
    """BOM, CRLF, кодировка — общие для всех файлов."""
    проблемы: list[dict] = []

    if данные.startswith(b"\xef\xbb\xbf"):
        проблемы.append({
            "вид": "BOM",
            "строка": 1,
            "слово": "",
            "текст": "файл начинается с BOM; в bash это часть shebang",
        })

    crlf = данные.count(b"\r\n")
    if crlf:
        проблемы.append({
            "вид": "CRLF",
            "строка": 0,
            "слово": "",
            "текст": f"{crlf} CRLF — shebang станет '#!/bin/bash\\r'",
        })

    try:
        данные.decode("utf-8")
    except UnicodeDecodeError as ошибка:
        проблемы.append({
            "вид": "НЕ-UTF8",
            "строка": 0,
            "слово": "",
            "текст": f"не декодируется в UTF-8: {ошибка}",
        })

    return проблемы


def проверить_файл(путь: Path) -> list[dict]:
    данные = путь.read_bytes()
    проблемы = проверить_формат(данные)

    try:
        текст = данные.decode("utf-8")
    except UnicodeDecodeError:
        return проблемы

    # Смешанный алфавит ищем ВЕЗДЕ: и в bash, и в Python.
    # Опечатка «sverху» нечеловекочитаема в любом языке.  # sora-scan: skip
    проблемы += найти_смешанные(текст)

    if путь.suffix.lower() == ".py":
        # ПОЧЕМУ ПРОВЕРКА СИНТАКСИСА ЗДЕСЬ, А НЕ ОТДЕЛЬНЫМ СКРИПТОМ.
        #
        # Ответ этого инструмента «всё чисто» — это разрешение
        # коммитить. Значит, инструмент обязан ловить и то, что файл
        # вообще не компилируется.
        #
        # Так и вышло: файл с поломанным продолжением строки проходил
        # проверку как «чистый», потому что смешанного алфавита в нём
        # не было — и синтаксической ошибки тоже не было. Сканер
        # молчал, потому что смотрел не туда.
        try:
            ast.parse(текст, filename=str(путь))
        except SyntaxError as ошибка:
            проблемы.append({
                "вид": "СИНТАКСИС",
                "строка": ошибка.lineno or 0,
                "слово": "",
                "текст": f"{ошибка.msg} (строка {ошибка.lineno})",
            })

    if это_bash(путь):
        for номер, строка in enumerate(текст.split("\n"), 1):
            if строка.startswith("\t"):
                проблемы.append({
                    "вид": "ТАБ",
                    "строка": номер,
                    "слово": "",
                    "текст": "строка начинается с таба — bash требует пробелы",
                })
        проблемы += найти_кириллицу_в_именах(текст)

    return проблемы


def файлы_для_проверки(корни: list[Path]) -> list[Path]:
    результат: list[Path] = []

    for корень in корни:
        if корень.is_file():
            результат.append(корень)
            continue
        if not корень.exists():
            continue
        for путь in sorted(корень.rglob("*")):
            if not путь.is_file() or ".git" in путь.parts:
                continue
            if путь.suffix.lower() in РАСШИРЕНИЯ or ИМЯ_СКРИПТА.match(путь.name):
                результат.append(путь)

    return результат


def главный() -> int:
    разбор = argparse.ArgumentParser(
        description="Смешанный алфавит, кириллица в именах bash, BOM и CRLF")
    разбор.add_argument("пути", nargs="*", default=["."],
                        help="что проверять (по умолчанию весь пакет)")
    разбор.add_argument("--json", action="store_true", help="вывод в JSON")
    разбор.add_argument("--quiet", action="store_true", help="только итог")
    арг = разбор.parse_args()

    файлы = файлы_для_проверки([Path(путь) for путь in арг.пути])

    if not файлы:
        print("  файлов не найдено по путям:", ", ".join(арг.пути))
        return 1

    отчёт: dict[str, list[dict]] = {}
    всего = 0

    for файл in файлы:
        проблемы = проверить_файл(файл)
        if проблемы:
            отчёт[str(файл)] = проблемы
            всего += len(проблемы)

    if арг.json:
        print(json.dumps(отчёт, ensure_ascii=False, indent=2))
        return 1 if всего else 0

    if арг.quiet:
        bash_штук = sum(1 for ф in файлы if это_bash(ф))
        print(f"  файлов: {len(файлы)} (bash: {bash_штук}), проблем: {всего}")
        return 1 if всего else 0

    print()
    print("═" * 66)
    print("  ПРОВЕРКА: смешанный алфавит, кириллица в именах bash, BOM, CRLF")
    print("═" * 66)
    bash_штук = sum(1 for ф in файлы if это_bash(ф))
    print(f"  проверено: {len(файлы)} файлов, из них bash: {bash_штук}")
    print()

    if всего == 0:
        print("  [ok] чисто.")
        print()
        print("  Русский в строках и комментариях — норма проекта, это не ошибка.")
        print("  Ошибка — слово, где смешались две азбуки: «sverху», «fайл».")  # sora-scan: skip
        return 0

    for имя, проблемы in отчёт.items():
        print(f"  ── {имя}")
        for проблема in проблемы:
            номер = f":{проблема['строка']}" if проблема["строка"] else ""
            print(f"     [{проблема['вид']}]{номер} {проблема['текст']}")
        print()

    print(f"  ВСЕГО: {всего}")
    return 1


if __name__ == "__main__":
    sys.exit(главный())
