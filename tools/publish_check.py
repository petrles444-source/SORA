#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Проверка публичной сборки на попадание настоящих ключей.

ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ ИНСТРУМЕНТ

Обычная проверка «есть ли в файлах строки, похожие на ключ» — слабая.
Она ищет по шаблону и молчит, когда шаблон не сработал. История такая:
ключи уже попадали в репозиторий, и проверка «похоже на ключ» это
не поймала, потому что смотрела не туда.

Здесь проверка УСТРАВШЕННАЯ. Берётся настоящий реестр, из него
достаются ВСЕ секретные значения — приватные ключи, PresharedKey,
приватный ключ сервера — и каждое ищется в публичной сборке как
точная подстрока.

    попало точно это значение  →  СТОП, ключ в публичном репозитории
    не нашлось                    →  можно публиковать

Это проверка факта, а не вида. Если ключ не совпал — его там нет,
как бы он ни выглядел.

ПОЧЕМУ ПОПАДАНИЕ НЕОБРАТИМО

Git хранит историю навсегда. Даже если удалить файл и сделать новый
коммит, старая версия остаётся в клонах у всех, кто успел
забрать репозиторий. Ключ придётся считать скомпрометированным:
отозвать, выпустить новый, разослать людям новые конфиги.

ЗАПУСК

  python tools/publish_check.py client/registry.json ПАПКА_СБОРКИ

КОД ВОЗВРАТА
  0 — публиковать можно
  1 — найдено совпадение, публиковать НЕЛЬЗЯ
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# Расширения, которые могут содержать текст и подлежат проверке.
ТЕКСТОВЫЕ = {
    ".py", ".sh", ".md", ".json", ".txt", ".html", ".htm", ".xml",
    ".yml", ".yaml", ".conf", ".cfg", ".ini", ".toml", ".csv", ".log",
}

# Расширения, которые ТОЧНО не содержат ключей в читаемом виде.
ДВОИЧНЫЕ = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".zip", ".gz",
            ".bz2", ".xz", ".exe", ".dll", ".so", ".bin", ".pdf"}


def собрать_секреты(реестр: Path) -> dict[str, str]:
    """Достать из реестра все секретные значения."""
    данные = json.loads(реестр.read_text(encoding="utf-8"))
    секреты: dict[str, str] = {}

    meta = данные.get("meta", {})

    # Приватные ключи сервера. Публичный — не секрет.
    for поле in ("server_private_key", "server_psk"):
        значение = meta.get(поле)
        if значение:
            секреты[f"meta.{поле}"] = значение

    # Приватные ключи и PresharedKey людей.
    for ник, пир in данные.get("peers", {}).items():
        for поле in ("private_key", "preshared_key"):
            значение = пир.get(поле)
            if значение:
                секреты[f"{ник}.{поле}"] = значение

    return секреты


def сканировать(папка: Path, секреты: dict[str, str]) -> list[tuple]:
    """Искать каждое секретное значение как точную подстроку."""
    находки: list[tuple] = []

    файлы = [f for f in sorted(папка.rglob("*"))
             if f.is_file() and ".git" not in f.parts]

    for файл in файлы:
        расширение = файл.suffix.lower()
        if расширение in ДВОИЧНЫЕ:
            continue

        try:
            содержимое = файл.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue

        for имя, значение in секреты.items():
            if значение and значение in содержимое:
                находки.append((файл, имя))

    return находки


def главный() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        print("Нужно: python tools/publish_check.py РЕЕСТР ПАПКА_СБОРКИ")
        return 1

    реестр = Path(sys.argv[1])
    папка = Path(sys.argv[2])

    if not реестр.exists():
        print("  реестр не найден:", реестр)
        return 1
    if not папка.is_dir():
        print("  папка сборки не найдена:", папка)
        return 1

    секреты = собрать_секреты(реестр)

    print()
    print("═" * 66)
    print("  ПРОВЕРКА ПУБЛИКАЦИИ: настоящие ключи в сборке")
    print("═" * 66)
    print(f"  реестр:    {реестр}")
    print(f"  сборка:    {папка}")
    print(f"  секретов проверено: {len(секреты)}")
    print()

    for имя in секреты:
        print(f"    • {имя}")

    находки = сканировать(папка, секреты)

    print()
    if находки:
        print(f"  НАЙДЕНО СОВПАДЕНИЙ: {len(находки)}")
        print()
        for файл, имя in находки:
            print(f"  [СТОП] {имя}")
            print(f"         в файле: {файл}")
        print()
        print("  ПУБЛИКОВАТЬ НЕЛЬЗЯ.")
        print("  Удалите эти файлы из сборки и проверьте заново.")
        return 1

    print("  [ok] Ни один настоящий ключ в сборке не найден.")
    print()
    print("  Проверка точная: искались реальные значения ключей,")
    print("  а не «похожие на ключ». Нет совпадения — нет ключа.")
    return 0


if __name__ == "__main__":
    sys.exit(главный())
