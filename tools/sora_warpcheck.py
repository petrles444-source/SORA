#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
СТЕНД ПРОВЕРКИ КЛЮЧА WARP — в Docker, изолированно.

ЧТО ЭТО ДЕЛАЕТ

    Берёт конфиг .conf, поднимает туннель amneziawg-go внутри
    одноразового контейнера, ждёт рукопожатия, гасит контейнер.
    Вердикт: сервер ответил или нет.

ПОЧЕМУ ЧЕРЕЗ DOCKER

    Туннель создаёт TUN-устройство и переключает маршруты. На
    вашей машине это дёрнуло бы сеть на всё время проверки.
    Внутри контейнера у него свой сетевой мир: свои адаптеры,
    свои маршруты. Ни ваши адаптеры, ни ваш основной
    AmneziaWG не затрагиваются.

    Это проверяемо, а не обещается: у контейнера свой адрес в
    сети 172.17.0.0/16 и свой маршрут по умолчанию, и хост о
    контейнере не знает ничего.

ЧТО ИЗМЕРЯЕТСЯ — И ЭТО ВАЖНО ПОНИМАТЬ

    Стенд отвечает на вопрос «отвечает ли сервер НА ЭТОТ
    АДРЕС». Он не отвечает на вопрос «работает ли ключ».

    Разница существенна. Часть публичных генераторов WARP
    требует регистрации реального адреса через бота в Telegram
    и отдают конфиг только на зарегистрированные адреса. Ключ,
    прекрасно работающий с телефона, из контейнера не
    ответит — и это скажет не о ключе, а об адресе.

    Поэтому вердикт «НЕ ОТВЕЧАЕТ» читается так: «сервер не
    ответил с этого адреса». Ни больше, ни меньше.

КАК ПОНЯТЬ, ЧТО ОШИБКА В САМОМ СТЕНДЕ, А НЕ В КЛЮЧЕ

    Стенд калибруется на заведомо рабочем ключе. Если рабочий
    ключ признан мёртвым — виноват стенд. Таблица ложных
    отрицательных результатов есть в docs/ПРОВЕРКА-КЛЮЧЕЙ.md.

ЗАПУСК

    # один ключ
    python tools/sora_warpcheck.py КОНФИГ.conf

    # подольше ждать
    python tools/sora_warpcheck.py КОНФИГ.conf --секунд 25

    # очередью по папке, с паузой
    python tools/sora_warpcheck.py --папка C:/configs --pause 25

    # только уникальные ключи, новые сверху
    python tools/sora_warpcheck.py --папка C:/configs --только-уникальные

ПЕРВЫЙ ЗАПУСК

    Образ собирается один раз (~120 МБ) и дальше кэшируется.

ЧЕГО НЕ ДЕЛАЕТ

    Не трогает основную сеть и основной AmneziaWG.
    Не печатает приватные ключи — ни в вывод, ни в отчёт.
    Не сканирует чужие хосты: обращается ровно к тому адресу,
    который указан в вашем собственном конфиге.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# «2.14 KiB received, 0 B sent» — в одном формате всегда.
ПЕРЕДАЧА = re.compile(
    r"([\d.]+)\s*(B|KiB|MiB|GiB)\s+received,\s*([\d.]+)\s*(B|KiB|MiB|GiB)\s+sent")

КОРЕНЬ = Path(__file__).resolve().parent.parent
ОБРАЗ = "sora-warpcheck:local"
DOCKERFILE = КОРЕНЬ / "tools" / "Dockerfile.warpcheck"
ИМЯ_КОНТЕЙНЕРА = "sora-warpcheck"
ИНТЕРФЕЙС = "wgt"

ОБЯЗАТЕЛЬНЫЕ = ("PrivateKey", "PublicKey", "Endpoint")

# Параметры обфускации. I1 меняет ФОРМУ пакета: если сервер
# настроен на I1, а клиент его не передал, сервер не примет
# ни одного пакета. Поэтому уходят все поля, а не выборочные.
ОБФУСКАЦИЯ = (
    "Jc", "Jmin", "Jmax",
    "S1", "S2", "S3", "S4",
    "H1", "H2", "H3", "H4",
    "I1", "I2", "I3", "I4", "I5",
)


# ────────────────────────────────  низкий уровень  ────────────────────────────

def докер(*аргументы: str, таймаут: int = 180) -> tuple[int, str, str]:
    """Прогнать команду docker и вернуть код с выводом."""
    итог = subprocess.run(
        ["docker", *аргументы],
        capture_output=True, text=True, encoding="utf-8",
        errors="replace", timeout=таймаут)
    return итог.returncode, итог.stdout or "", итог.stderr or ""


def образ_собран() -> bool:
    код, вывод, _ = докер(
        "images", "--format", "{{.Repository}}:{{.Tag}}", таймаут=60)
    return ОБРАЗ in вывод.split()


def собрать_образ() -> bool:
    """Собрать образ стенда. Дальше Docker отдаёт его из кэша."""
    print("  ── сборка образа (один раз, дальше из кэша) ──")
    код, вывод, ошибка = докер(
        "build", "-f", str(DOCKERFILE), "-t", ОБРАЗ, str(КОРЕНЬ), таймаут=900)
    if код != 0:
        print("  [!] образ не собрался:")
        for строка in (вывод + ошибка).splitlines()[-12:]:
            print("     ", строка)
        return False
    print("  образ готов")
    return True


def убрать_контейнер() -> None:
    код, _, _ = докер("rm", "-f", ИМЯ_КОНТЕЙНЕРА, таймаут=60)
    if код == 0:
        print("  (убран контейнер от прошлого запуска)")


# ────────────────────────────────  разбор конфига  ───────────────────────────

def разобрать_конфиг(путь: Path) -> tuple[dict[str, str], list[str]]:
    """
    Достать из .conf поля для контейнера.

    Возвращает (поля, замечания). Приватный ключ наружу не
    печатается — он нужен только для передачи в контейнер.
    """
    поля: dict[str, str] = {}
    замечания: list[str] = []

    текст = путь.read_text(encoding="utf-8", errors="ignore")
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#") or строка.startswith("["):
            continue
        if "=" in строка:
            имя, значение = строка.split("=", 1)
            поля[имя.strip()] = значение.strip()

    for нужно in ОБЯЗАТЕЛЬНЫЕ:
        if not поля.get(нужно):
            замечания.append(f"нет обязательного поля {нужно}")

    return поля, замечания


def собрать_ini(поля: dict[str, str]) -> tuple[str, str]:
    """
    Собрать INI-конфиг для `awg setconf`.

    Возвращает (текст, адрес сервера).

    ТРИ ТОНКОСТИ, КОТОРЫЕ СТОИЛИ ОТЛАДКИ

    1. Заголовок [Interface] ОБЯЗАТЕЛЕН. Без него парсер
       отвечает «Line unrecognized» на первую же строку.

    2. Поле Address с адресом IPv6 через запятую
       («172.16.0.2,2606:…») тоже не принимается. Оно нам и не
       нужно: адрес на туннеле мы назначаем сами, проверенным
       адресом из сети 172.31.0.0/24.

    3. Имя сервера резолвится ЗДЕСЬ, на хосте, и в контейнер
       уходит готовый IP. Внутри контейнера DNS может не
       работать, а нерезолвенное имя означает «пакет не ушёл» —
       то есть ложный отрицательный вердикт на живом ключе.
    """
    endpoint = поля.get("Endpoint", "")
    хост, _, порт = endpoint.rpartition(":")
    if not хост:
        хост, порт = endpoint, "0"

    ip = ""
    try:
        ip = socket.getaddrinfo(хост, None, socket.AF_INET)[0][4][0]
    except (socket.gaierror, IndexError):
        ip = ""

    цель = f"{ip}:{порт}" if ip else endpoint

    строки = ["[Interface]", f"PrivateKey = {поля.get('PrivateKey', '')}"]
    for имя in ОБФУСКАЦИЯ:
        if поля.get(имя):
            строки.append(f"{имя} = {поля[имя]}")

    строки += ["", "[Peer]",
               f"PublicKey = {поля.get('PublicKey', '')}",
               "AllowedIPs = 0.0.0.0/0",
               f"Endpoint = {цель}"]

    if поля.get("PresharedKey"):
        строки.append(f"PresharedKey = {поля['PresharedKey']}")

    return "\n".join(строки) + "\n", цель


def показать_конфиг(текст: str) -> None:
    """Напечатать конфиг для проверки глазами. Ключи скрыты."""
    print("  ── конфиг, который уйдёт в контейнер ──")
    for строка in текст.splitlines():
        имя = строка.split("=", 1)[0].strip().lower()
        if имя in ("privatekey", "presharedkey", "psk"):
            значение = строка.split("=", 1)[1].strip()
            print(f"    {строка.split('=')[0].strip()} = <скрыт, {len(значение)} симв.>")
        else:
            укоротить = 72
            тек = строка[:укоротить] + "…" if len(строка) > укоротить else строка
            print("    " + тек)
    print()


