# Скрипт внутри контейнера. Имена переменных латиницей:
# кириллица в shell ломается непредсказуемо.
СКРИПТ = r"""
mkdir -p /var/run/amneziawg

# STDIN ДЕРЖИМ ОТКРЫТЫМ.
# amneziawg-go живёт, пока жив stdin. Конструкция
# `cat conf | amneziawg-go` закрывает трубу сразу после cat, и
# процесс уходит на EOF. Подстановка sleep в конец потока
# держит канал открытым гарантированно.
( sleep 600 ) | amneziawg-go wgt > /tmp/log 2>&1 &
sleep 3

# ЖИВОСТЬ ПРОВЕРЯЕМ НЕ ЧЕРЕЗ kill -0 $PID.
# В конвейере $! указывает не на процесс amneziawg-go, и
# проверка врёт: живой процесс объявляется мёртвым. Настоящая
# проверка — отвечает ли UAPI-сокет.
if ! awg show wgt > /dev/null 2>&1; then
  echo "СОСТОЯНИЕ=НЕТ_ИНТЕРФЕЙСА"
  grep -vE '^\s*[│┌└├]' /tmp/log | head -5
  exit 1
fi
echo "СОСТОЯНИЕ=ИНТЕРФЕЙС_ЕСТЬ"

# КОНФИГ ПРИМЕНЯЕМ ЧЕРЕЗ UAPI, А НЕ ЧЕРЕЗ STDIN.
# Конфиг, подложенный в stdin, в этой версии бинарника
# устройству не передаётся: туннель поднимается пустым, пир
# отсутствует, шифровать нечего, а счётчики показывают
# исходящие байты — их пишет ядро в TUN независимо от того,
# читает ли их кто-нибудь. Снаружи это неотличимо от
# «ключ отправил, сервер молчит».
echo "SETCONF"
awg setconf wgt /warp/peer.ini 2>&1

sleep 1
# Проверка по слову, а не по отступу. В выводе `awg show`
# строка peer начинается В КОЛОНКЕ 0, тогда как public key и
# остальные поля интерфейса сдвинуты на два пробела. Шаблон
# вида `^  peer:` не срабатывает никогда, и проверка объявляет
# исправным туннель пустым.
if awg show wgt | grep -q 'peer:'; then
  echo "ПИР_ЕСТЬ=да"
else
  echo "ПИР_ЕСТЬ=НЕТ"
  echo "--- что вижу в устройстве ---"
  awg show wgt 2>&1
  echo "--- лог setconf ---"
  exit 1
fi

ip link set wgt up 2>/dev/null || true
ip addr add 172.31.0.1/24 dev wgt 2>/dev/null || true

# МАРШРУТ ПО УМОЛЧАНИЮ ЗАМЕНЯЕМ, А НЕ ДОБАВЛЯЕМ.
# У контейнера уже есть свой default с меньшей метрикой;
# добавленный без удаления старого не сработает, и пакеты
# уйдут мимо туннеля. При этом ping может показать 0%
# потерь — он просто пойдёт обычной дорогой контейнера, и
# проверка сообщит об успехе, хотя туннель не участвовал.
ip route del default 2>/dev/null || true
ip route add default dev wgt 2>/dev/null || true

for i in $(seq 1 SECONDS_WAIT); do
  ping -c1 -W1 1.1.1.1 > /dev/null 2>&1 || true
  sleep 1
done

echo "--- AWG_SHOW ---"
awg show wgt 2>&1
echo "--- PING ---"
ping -c3 -W3 1.1.1.1 2>&1 | tail -3
echo "--- ЛОГ_БИНАРНИКА ---"
grep -vE '^\s*[│┌└├]' /tmp/log | head -6
echo "--- КОНЕЦ ---"
"""


def проверить_один(путь: Path, секунд: int = 10,
                  показать: bool = True) -> dict:
    """Одна проверка. Возвращает словарь с вердиктом."""
    начало = time.time()
    результат = {
        "файл": путь.name,
        "вердикт": "НЕИЗВЕСТНО",
        "деталей": [],
        "секунд": 0.0,
    }

    поля, замечания = разобрать_конфиг(путь)
    результат["деталей"] += замечания
    if замечания:
        результат["вердикт"] = "БИТЫЙ КОНФИГ"
        результат["секунд"] = round(time.time() - начало, 1)
        return результат

    ini, цель = собрать_ini(поля)
    результат["endpoint"] = цель
    результат["есть_i1"] = bool(поля.get("I1"))
    результат["есть_preshared"] = bool(поля.get("PresharedKey"))

    if показать:
        print(f"  сервер:   {цель}")
        print(f"  I1:       {'есть' if результат['есть_i1'] else 'НЕТ'}")
        показать_конфиг(ini)

    каталог = Path(tempfile.mkdtemp(prefix="sora-warp-"))
    (каталог / "peer.ini").write_text(ini, encoding="utf-8", newline="\n")

    try:
        код, вывод, ошибка = докер(
            "run", "--rm", "--name", ИМЯ_КОНТЕЙНЕРА,
            # NET_ADMIN — право менять сеть, /dev/net/tun — само
            # устройство. Одно без другого не работает: право не
            # создаёт файл устройства, и amneziawg-go падает с
            # «/dev/net/tun does not exist».
            "--cap-add", "NET_ADMIN",
            "--device", "/dev/net/tun",
            "-v", f"{каталог}:/warp:ro",
            ОБРАЗ, "sh", "-c",
            СКРИПТ.replace("SECONDS_WAIT", str(секунд)),
            таймаут=секунд + 150,
        )
    finally:
        убрать_контейнер()
        shutil.rmtree(каталог, ignore_errors=True)

    результат["секунд"] = round(time.time() - начало, 1)
    текст = вывод + ошибка

    if "СОСТОЯНИЕ=НЕТ_ИНТЕРФЕЙСА" in текст:
        результат["вердикт"] = "НЕ ПОДНЯЛСЯ"
    elif "ПИР_ЕСТЬ=НЕТ" in текст:
        результат["вердикт"] = "КОНФИГ НЕ ПРИНЯТ"
        результат["деталей"].append(
            "конфиг не применился — вероятно, формат поля не поддержится")

    # Разбор состояния. Собираем факты, вердикт ставим в конце.
    есть_handshake = False
    отправлено = 0.0
    принято = 0.0

    for строка in текст.splitlines():
        ч = строка.strip()
        if "latest handshake:" in ч and "never" not in ч:
            есть_handshake = True
            результат["деталей"].append(ч)
        elif ч.startswith("transfer:"):
            результат["деталей"].append(ч)
            разобрано = разобрать_передачу(ч)
            if разобрано:
                принято, отправлено = разобрано
        elif "packet loss" in ч:
            результат["деталей"].append(ч)
        elif "Line unrecognized" in ч or "parsing error" in ч:
            результат["деталей"].append(ч)

    результат["есть_handshake"] = есть_handshake
    результат["отправлено_байт"] = отправлено
    результат["принято_байт"] = принято

    if есть_handshake:
        результат["вердикт"] = "ОТВЕТИЛ"
    elif отправлено > 0:
        результат["вердикт"] = "ОТПРАВИЛ, НЕ ОТВЕТИЛ"
        результат["деталей"].append(
            "пакеты шифруются и уходят, ответа нет: сервер не отвечает "
            "с этого адреса")
    elif результат["вердикт"] == "НЕИЗВЕСТНО" and принято == 0:
        результат["вердикт"] = "НЕ ОТВЕЧАЕТ"

    return результат


def разобрать_передачу(строка: str) -> tuple[float, float] | None:
    """
    Разобрать «transfer: 1.23 KiB received, 4.56 KiB sent».

    Возвращает (принято, отправлено) в байтах.

    Разбор идёт регулярным выражением, а не делением строки по
    словам. При делении по «sent» в начало числа отправленного
    попадает всё, что стоит до слова «received», и отправленное
    молча читается как принятое: вердикт получается неверным при
    полностью рабочем туннеле.
    """
    совпало = ПЕРЕДАЧА.search(строка)
    if not совпало:
        return None
    принято = в_байты(совпало.group(1), совпало.group(2))
    отправлено = в_байты(совпало.group(3), совпало.group(4))
    return принято, отправлено


def в_байты(число: str, единица: str) -> float:
    """«2.14», «KiB» → байты."""
    множитель = {"B": 1, "KiB": 1024, "MiB": 1024 ** 2, "GiB": 1024 ** 3}
    try:
        return float(число) * множитель.get(единица, 1)
    except ValueError:
        return 0.0


# ────────────────────────────────  очередь  ───────────────────────────────

def уникальные_по_ключу(файлы: list[Path]) -> list[Path]:
    """Оставить по одному файлу на каждый открытый ключ."""
    увиденные: set[str] = set()
    порядок: list[Path] = []
    for путь in файлы:
        поля, зам = разобрать_конфиг(путь)
        if зам:
            continue
        ключ = поля.get("PublicKey", "")
        if ключ and ключ not in увиденные:
            увиденные.add(ключ)
            порядок.append(путь)
    return порядок


