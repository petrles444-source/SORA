    for деталь in р["деталей"]:
        print(f"    · {деталь}")
    print()

    if р["вердикт"] == "ОТПРАВИЛ, НЕ ОТВЕТИЛ":
        print("  ЧТО ЭТО ЗНАЧИТ")
        print("    Туннель работает: пакеты зашифрованы и ушли.")
