def скачать(адрес, заголовки=None, сколько=0, таймаут=ТАЙМАУТ):
    """GET-запрос. Возвращает (текст, заголовки) либо бросает исключение."""
    req = urllib.request.Request(адрес, headers=заголовки or {
        "User-Agent": "SORA-Check/1.0"})
    ctx = ssl.create_default_context()
    with urllib.request.urlopen(req, timeout=таймаут, context=ctx) as отв:
        тело = отв.read(сколько if сколько else -1)
        return тело, отв.headers


def мой_адрес():
    """Внешний IPv4 глазами разных сервисов.

    Спрашиваем дважды у разных: если один ответил, а второй нет —
    это само по себе говорит о том, что связь нестабильна.

    IPv4 запрашивается ЯВНО. Без этого icanhazip отдаёт IPv6, если
    тот доступен, и сравнение с адресом сервера всегда давало бы
    «туннель не работает» на машине, где всё настроено верно.
    """
    ответы = {}
    for имя, адрес in (("ipify", "https://api.ipify.org"),
                       ("icanhazip", "https://icanhazip.com")):
        try:
            тело, _ = скачать(адрес, сколько=200)
            ответы[имя] = _только_ipv4(
                тело.decode("utf-8", "replace").strip())
        except Exception:
            ответы[имя] = None
    return ответы


def _только_ipv4(текст):
    """Достаёт из ответа IPv4, а если там IPv6 — возвращает None.

    Ответ сервиса может содержать что угодно: HTML, пояснение,
    адрес. Для сравнения с адресом сервера годится только IPv4.
    """
    m = re.search(r"\b(\d{1,3}(?:\.\d{1,3}){3})\b", текст)
    return m.group(1) if m else None


def _похоже_на_ip(текст):
    """Ответ сервиса — это адрес, а не страница?

    Первая версия проверки DNS принимала ответ «как есть». Сайт
    myip.ms при ошибке отдаёт HTML, и проверка радостно сообщала
    «DNS идёт через туннель», разглядев в верстке страницы
    доказательство защищённости. Вывод был выдуманным.
    """
    if not текст:
        return False
    т = текст.strip()
    if "<" in т or "DOCTYPE" in т or len(т) > 64:
        return False
    return bool(re.fullmatch(r"[0-9a-fA-F:.]{3,45}", т))


def cloudflare_sled():
    """Спрашивает Cloudflare: включён ли WARP и где выход.

    Ответ приходит текстом, где есть прямая строка warp=on либо
    warp=off. Это единственный надёжный способ узнать, что именно
    сейчас настроено, не гадая по диапазону адресов.

    Нужен потому, что у пользователя УЖЕ может быть включён WARP.
    Первая версия проверки об этом не знала и называла адрес
    Cloudflare утечкой, хотя он шёл через туннель Cloudflare.
    """
    try:
        тело, _ = скачать("https://www.cloudflare.com/cdn-cgi/trace",
                          сколько=2000)
        сырой = тело.decode("utf-8", "replace")
        поля = {}
        for стр in сырой.splitlines():
            if "=" in стр:
                k, v = стр.split("=", 1)
                поля[k.strip()] = v.strip()
        if not поля:
            return None
        return {
            "warp": поля.get("warp", "?"),
            "loc": поля.get("loc", "?"),
            "ip": поля.get("ip", ""),
            "gateway": поля.get("gateway", "?"),
        }
    except Exception:
        return None


def мой_адрес_v6():
    """Внешний IPv6. None — если IPv6 нет или он не работает."""
    try:
        тело, _ = скачать("https://api6.ipify.org")
        v = тело.decode("utf-8", "replace").strip()
        return v or None
    except Exception:
        return None


def мой_dns():
    """Каким резолвером обрабатываются запросы.

    Сайты вроде whoami.akamai.net отвечают адресом того DNS-сервера,
    который обработал запрос. Если ответ российский — запрос ушёл мимо
    туннеля.

    ВАЖНО. Ответ фильтруется: пропускается только то, что похоже на
    адрес. Иначе страница с ошибкой принималась за доказательство
    защищённости.
    """
    ответы = {}
    for имя, адрес in (
            ("akamai", "https://whoami.akamai.net/akamai.akamai.net"),
            ("myip_ms", "https://myip.ms/resolver/ns")):
        try:
            тело, _ = скачать(адрес, сколько=300)
            сырой = тело.decode("utf-8", "replace").strip()
            # myip.ms отдаёт несколько имён резолвера, берём все
            адреса = re.findall(r"\b(?:\d{1,3}\.){3}\d{1,3}\b", сырой)
            if адреса and _похоже_на_ip(адреса[0]):
                ответы[имя] = ", ".join(адреса[:4])
            else:
                ответы[имя] = None      # HTML или мусор — это не ответ
        except Exception:
            ответы[имя] = None
    return ответы


def скорость(байт=3 * 1024 * 1024, адрес=None):
    """Замер скорости скачивания. Возвращает байт в секунду."""
    адреса = [адрес] if адрес else [
        "https://speed.cloudflare.com/__down?bytes=%d" % байт,
        "https://proof.ovh.net/files/1Mb.dat",
    ]
    for a in адреса:
        try:
            начало = time.time()
            req = urllib.request.Request(a, headers={
                "User-Agent": "SORA-Check/1.0"})
            ctx = ssl.create_default_context()
            всего = 0
            with urllib.request.urlopen(req, timeout=25, context=ctx) as отв:
                while всего < байт:
                    кусок = отв.read(65536)
                    if not кусок:
                        break
                    всего += len(кусок)
            конец = time.time()
            if конец > начало and всего > 100000:
                return всего / (конец - начало)
        except Exception:
            continue
    return None


