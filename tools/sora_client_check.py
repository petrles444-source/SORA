def проверить_туннель(p, сервер):
    """Разбираемся, ЧТО ИМЕННО сейчас защищает трафик.

    У пользователя может быть включён Cloudflare WARP — бесплатный,
    уже работает, лимиты большие. Первая версия проверки знала
    только про SORA и в случае WARP радостно сообщала «туннель не
    работает», хотя туннель был. Проверка обязана отличать «не
    работает» от «работает, но не тот, который мы ждали».
    """
    след = cloudflare_sled()
    warp_включен = bool(след and след.get("warp") == "on")

    if след:
        if warp_включен:
            p.append(Проверка(
                "C0", "Cloudflare WARP включён", ОК,
                "выход: %s, адрес %s"
                % (след.get("loc", "?"), след.get("ip", "")[:40])))
        else:
            p.append(Проверка(
                "C0", "Cloudflare WARP выключен", НЕПРОВЕРЕНО,
                "trace отвечает, warp=off"))

    ответы = мой_адрес()
    живые = {k: v for k, v in ответы.items() if v}

    if not живые:
        p.append(Проверка("C1", "Внешний адрес определить не удалось",
                          НЕПРОВЕРЕНО,
                          "оба сервиса молчат: нет интернета вовсе "
                          "или всё заблокировано"))
        return

    адреса = set(живые.values())
    если_другой_туннель = warp_включен

    if len(адреса) == 1:
        p.append(Проверка("C1", "Внешний адрес виден", ОК,
                          живые[list(живые)[0]]))
    else:
        p.append(Проверка("C1", "Сервисы дают разные адреса", СОВЕТ,
                          ", ".join(sorted(адреса)) +
                          " — часть трафика, возможно, идёт мимо туннеля"))

    if сервер and сервер in адреса:
        p.append(Проверка("C2", "Туннель SORA работает", ОК,
                          "наружу виден адрес сервера %s" % сервер))
        return

    if если_другой_туннель:
        p.append(Проверка(
            "C2", "SORA не подключён, но трафик защищён", СОВЕТ,
            "сейчас работает WARP (выход %s), а не наш сервер %s. "
            "Это не поломка: WARP — другой, тоже рабочий туннель."
            % (след.get("loc", "?") if след else "?", сервер),
            "если проверяете SORA — подключитесь в Amnezia и запустите "
            "проверку снова"))
        return

    p.append(Проверка("C2", "Никакого туннеля не видно", ПРОБЛЕМА,
                      "ожидали %s, а видно %s"
                      % (сервер, ", ".join(sorted(адреса))),
                      "проверьте, подключён ли VPN. Если ничего не "
                      "подключено — трафик идёт открыто."))


def проверить_dns(p):
    ответы = мой_dns()
    живые = {k: v for k, v in ответы.items() if v}

    if not живые:
        p.append(Проверка("D1", "DNS-резолвер определить не удалось",
                          НЕПРОВЕРЕНО,
                          "сервисы, показывающие резолвер, недоступны "
                          "или отдали не адрес. Проверить утечку DNS "
                          "сейчас нечем."))
    else:
        текст = " | ".join("%s: %s" % (k, v[:60]) for k, v in живые.items())
        # Российские публичные резолверы, утечка которых ищется
        подозрительные = ("77.88", "213.180", "195.46", "194.85",
                          "87.250", "89.109", "217.226", "109.252")
        нашли = [s for s in подозрительные if any(
            s in v for v in живые.values())]

        if нашли:
            p.append(Проверка("D1", "DNS уходит мимо туннеля", ПРОБЛЕМА,
                              текст,
                              "виден российский резолвер (%s). Весь "
                              "список открытых вами сайтов известен "
                              "провайдеру. В конфиге должен быть "
                              "DNS = 10.77.0.1" % ", ".join(нашли)))
        else:
            p.append(Проверка("D1", "DNS идёт через туннель", ОК, текст))

    локальные = мой_dns_локально()
    if локальные:
        p.append(Проверка("D2", "Резолверы, прописанные в системе",
                          СОВЕТ,
                          ", ".join(локальные[:5]) +
                          " — если здесь чужой адрес, клиент может "
                          "использовать его мимо туннеля"))


def проверить_ipv6(p):
    """IPv6 сам по себе не утечка.

    Утечка — это когда IPv6 идёт мимо туннеля. Но если включён WARP,
    то его IPv6 (2a09:bac5::) идёт ЧЕРЕЗ туннель Cloudflare, и
    называть это утечкой неверно: это просто чужой адрес.

    Первая версия проверки не различала эти случаи и объявляла
    утечкой адрес, который на самом деле шёл через работающий VPN.
    """
    v6 = мой_адрес_v6()
    if v6 is None:
        p.append(Проверка("E1", "Утечки IPv6 нет", ОК,
                          "IPv6 наружу не отвечает — утекать нечему"))
        return

    след = cloudflare_sled()
    через_warp = bool(след and след.get("warp") == "on")

    if через_warp:
        p.append(Проверка(
            "E1", "IPv6 идёт через WARP", ОК,
            "%s — адрес Cloudflare, он идёт через туннель. "
            "Это не утечка." % v6[:40]))
        return

    p.append(Проверка(
        "E1", "УТЕЧКА IPv6", ПРОБЛЕМА,
        "наружу виден IPv6 %s, и он НЕ принадлежит туннелю" % v6,
        "в конфиге должно быть AllowedIPs = 0.0.0.0/0, ::/0 — иначе "
        "IPv6 пойдёт напрямую, мимо VPN. Либо отключите IPv6 в системе."))


def проверить_маршрут(p, сервер):
    if not сервер:
        p.append(Проверка("F1", "Маршрут до сервера", НЕПРОВЕРЕНО,
                          "адрес сервера не указан"))
        return
    строки = маршрут_к_адресу(сервер)
    if not строки:
        p.append(Проверка("F1", "Маршрут до сервера", НЕПРОВЕРЕНО,
                          "traceroute недоступен или не ответил"))
        return
    пингвинг = any(re.search(r"\b(\d+)\s*ms", s) for s in строки)
    if пингвинг:
        p.append(Проверка("F1", "Маршрут до сервера прослеживается", ОК,
                          "%d узлов до сервера" % len(строки)))
    else:
        p.append(Проверка("F1", "Маршрут до сервера не отвечает",
                          СОВЕТ,
                          "сервер не ответил на traceroute — это "
                          "нормально, он может не отвечать на ping"))


def скорость_туннеля(p, сервер):
    """Замер скорости С УЧЁТОМ того, работает ли туннель.

    Без туннеля замер показывает скорость домашнего канала, и оценивать
    её как «медленный VPN» бессмысленно. Первая версия проверки не
    учитывала этого и называла 6 Мбит/с проблемой, хотя VPN в этот
    момент был выключен и никакого отношения к этим цифрам не имел.
    """
    байт_в_сек = скорость()
    if байт_в_сек is None:
        p.append(Проверка("G1", "Скорость", НЕПРОВЕРЕНО,
                          "сервисы замера недоступны"))
        return

    мбит = байт_в_сек * 8 / 1_000_000

    # Туннель есть ли наш SORA, ли включён WARP.
    # Первая версия смотрела только на SORA и обрадывалась
    # «туннель выключен» в момент, когда WARP работает как и понятно.
    sora_жив = any(
        пр.код == "C2" and пр.уровень == ОК for пр in p)
    warp_жив = any(
        пр.код == "C0" and пр.уровень == ОК for пр in p)

    if not (sora_жив or warp_жив):
        p.append(Проверка(
            "G1", "Скорость: туннеля нет", НЕПРОВЕРЕНО,
            "%.1f Мбит/с — это скорость вашего обычного канала. "
            "Ни SORA, ни WARP не видно." % мбит,
            "включите любой VPN и запустите проверку снова"))
        return

    через = "SORA" if sora_жив else "WARP"

    if мбит >= 50:
        уровень = ОК
    elif мбит >= 10:
        уровень = СОВЕТ
    else:
        уровень = ПРОБЛЕМА

    p.append(Проверка(
        "G1", "Скорость через %s" % через, уровень,
        "%.1f Мбит/с" % мбит,
        "низкая скорость обычно означает домашний канал, а не сервер. "
        "Сравните с замером при выключенном VPN: разница покажет, "
        "насколько мешает сам туннель." if мбит < 50 else ""))


def проверить_kill_switch(p):
    """Kill switch проверяется по-разному на разных системах.

    На Windows полноценно не проверяется: нужен доступ к WFP.
    Здесь честно говорим, что проверить нельзя.
    """
    if os.name == "nt":
        p.append(Проверка("H1", "Kill switch", НЕПРОВЕРЕНО,
                          "на Windows из пользовательского режима не "
                          "проверяется: нужен доступ к правилам брандмауэра "
                          "через WFP или netsh"))
        return
    try:
        p2 = subprocess.run(["ip", "rule"], capture_output=True, text=True,
                            timeout=10)
        есть_метрика = "0x" in (p2.stdout or "")
        p.append(Проверка("H1", "Маршруты с приоритетом", СОВЕТ if есть_метрика else НЕПРОВЕРЕНО,
                          "правила маршрутизации присутствуют" if есть_метрика
                          else "правила не читаются",
                          "проверьте вручную: ip rule list"))
    except Exception:
        p.append(Проверка("H1", "Kill switch", НЕПРОВЕРЕНО,
                          "команда ip rule недоступна"))


