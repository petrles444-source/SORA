def мой_dns_локально():
    """Какие DNS прописаны в системе — без туннеля."""
    if os.name == "nt":
        try:
            p = subprocess.run(["ipconfig", "/all"], capture_output=True,
                               text=True, errors="replace", timeout=10)
            найдено = re.findall(r"(\d+\.\d+\.\d+\.\d+)", p.stdout or "")
            уникальные = []
            for a in найдено:
                if a not in уникальные:
                    уникальные.append(a)
            return уникальные[:8]
        except Exception:
            return []
    try:
        with open("/etc/resolv.conf", encoding="utf-8") as f:
            return re.findall(r"nameserver\s+(\S+)", f.read())
    except OSError:
        return []


def маршрут_к_адресу(адрес):
    """Показывает, каким интерфейсом пойдёт трафик к серверу."""
    if os.name == "nt":
        try:
            p = subprocess.run(["tracert", "-d", "-h", "6", "-w", "800",
                                адрес], capture_output=True, text=True,
                               errors="replace", timeout=40)
            строки = [s for s in (p.stdout or "").splitlines()[2:] if s.strip()]
            return строки[:6]
        except Exception:
            return []
    try:
        p = subprocess.run(["traceroute", "-n", "-w", "1", "-q", "1",
                            "-m", "6", адрес], capture_output=True, text=True,
                           errors="replace", timeout=40)
        return [s for s in (p.stdout or "").splitlines() if s.strip()][:6]
    except Exception:
        return []


def интерфейсы_windows():
    """Список сетевых интерфейсов — ищем туннельный."""
    if os.name != "nt":
        return []
    try:
        p = subprocess.run(["ipconfig", "/all"], capture_output=True,
                           text=True, errors="replace", timeout=10)
        найдено = []
        for s in (p.stdout or "").splitlines():
            t = s.strip()
            if not t or t.endswith(":"):
                continue
            # заголовок описания адаптера
            # Класс [А-ЯA-Z] — «заглавная буква, хоть кириллица,
            # хоть латиница». Смешение здесь ЗАМЫСЛЕНО: так ловится
            # заголовок описания адаптера на любой системе.
            if (
                re.match(r"^[А-ЯA-Z].{0,60}(adapter|Адаптер)", s)  # sora-scan: skip
                or ("Description" in s or "Описание" in s)
            ):
                найдено.append(t)
        return найдено[:10]
    except Exception:
        return []


