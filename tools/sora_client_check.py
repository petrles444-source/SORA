def показать(p, подробно):
    print()
    print("═" * 74)
    print("  SORA: ПРОВЕРКА С КЛИЕНТА — %s"
          % datetime.datetime.now().strftime("%d.%m.%Y %H:%M"))
    print("═" * 74)

    по = {}
    for пр in p:
        г = ГРУППЫ.get(пр.код[0], "ПРОЧЕЕ")
        по.setdefault(г, []).append(пр)

    for г, список in по.items():
        print()
        print("%s%s%s" % (ЖИР, г, СБР))
        for пр in список:
            цв = ЦВЕТ[пр.уровень]
            # Склейка, а не %-шаблон: в шаблоне девять мест подстановки
            # при восьми аргументах, и Python падал на первой же строке.
            строка = "  " + цв + ЗНАК[пр.уровень] + СБР
            строка += " " + СЕР + пр.код.ljust(6) + СБР + " " + пр.название
            if пр.подробно:
                строка += "  " + ЖЁЛ + "— " + пр.подробно + СБР
            print(строка)
            if пр.совет and подробно:
                print("       " + ЖЁЛ + "что делать: " + пр.совет + СБР)

    всего = len(p)
    ок = sum(1 for x in p if x.уровень == ОК)
    пр = sum(1 for x in p if x.уровень == ПРОБЛЕМА)
    нп = sum(1 for x in p if x.уровень == НЕПРОВЕРЕНО)
    св = sum(1 for x in p if x.уровень == СОВЕТ)

    print()
    print("═" * 74)
    print("  проверок %d    %sок %d%s    %sпроблем %d%s    %sне проверено %d%s    %sсоветов %d%s"
          % (всего, ЗЕЛ, ок, СБР, КРАС, пр, СБР, СЕР, нп, СБР, ЖЁЛ, св, СБР))
    if нп:
        print("  %s«не проверено» — это не «всё хорошо».%s" % (СЕР, СБР))
    print("═" * 74)
    print()
    return пр


