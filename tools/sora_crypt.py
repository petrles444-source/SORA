def главный() -> int:
    аргументы = sys.argv[1:]

    # Файл перетащили на программу — шифруем без вопросов
    if аргументы and аргументы[0] == "--decrypt":
        if len(аргументы) < 2:
            print("  Нужно указать файл: python sora_crypt.py --decrypt файл.enc")
            return 1
        глобальный_путь = разобрать_путь(аргументы[1])
        пароль = спросить_пароль(для_расшифровки=True)
        try:
            данные = расшифровать(глобальный_путь, пароль)
        except ValueError as ошибка:
            print(f"  Не получилось: {ошибка}")
            return 1
        имя = глобальный_путь.name
        if имя.endswith(РАСШИРЕНИЕ):
            имя = имя[:-len(РАСШИРЕНИЕ)]
        цель = глобальный_путь.with_name(имя + ".расшифровано")
        цель.write_bytes(данные)
        print(f"  [ok] {цель}")
        return 0

    if аргументы:
        глобальный_путь = разобрать_путь(аргументы[0])
        пароль = спросить_пароль()
        цель = зашифровать(глобальный_путь, пароль)
        проверить_результат(глобальный_путь, цель, пароль)
        print(f"  [ok] {цель}")
        print("  Проверено: файл расшифровывается обратно без потерь.")
        return 0

    # Без аргументов — меню
    print()
    print("═" * 60)
    print("  ШИФРОВАЛЬЩИК ФАЙЛОВ")
    print("═" * 60)
    print()
    print("  1 — зашифровать файл")
    print("  2 — расшифровать файл")
    print("  3 — как это работает")
    print("  0 — выход")
    print()

    while True:
        выбор = input("  Выбор: ").strip()

        if выбор == "1":
            действие_зашифровать()
            print()
            input("  Enter — в меню")
        elif выбор == "2":
            действие_расшифровать()
            print()
            input("  Enter — в меню")
        elif выбор == "3":
            показать_справку()
            print()
            input("  Enter — в меню")
        elif выбор in ("0", "q", "в", "x"):
            print()
            print("  Выход.")
            return 0
        elif выбор == "":
            return 0
        else:
            print(f"  Не понял: «{выбор}». Введите 0, 1, 2 или 3.")


if __name__ == "__main__":
    sys.exit(главный())
