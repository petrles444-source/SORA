#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ШИФРОВАЛЬЩИК ФАЙЛОВ — простой, без сети и без установки.

ЗАЧЕМ

Ключи от VPN лежат в файле registry.json. Если он попадёт куда не
следовало — их придётся менять всем людям. Файл маленький, но
размер значения не имеет: в нём ключ от сервера и ключи всех, кто
подключён.

Программа берёт любой файл, шифрует его паролем и кладёт рядом.
Обратно — расшифровывает тем же паролем. Сети не касается вообще.

КАК ПОЛЬЗОВАТЬСЯ

Зашифровать:
    1. Запустить программу, выбрать «1»
    2. Ввести путь к файлу (или перетащить файл на программу)
    3. Ввести пароль дважды

    Либо одной строкой:
        python sora_crypt.py файл.txt

Расшифровать:
    1. Запустить, выбрать «2»
    2. Указать файл с расширением .enc
    3. Ввести пароль

    Либо одной строкой:
        python sora_crypt.py --decrypt файл.txt.enc

ОТКУДА ВЗЯТЬ ФАЙЛ ДЛЯ ШИФРОВАНИЯ

    Путь к реестру: client/registry.json внутри папки SORA.
    Полностью: <ваша папка>/SORA/client/registry.json

ЧЕМ ШИФРУЕТ

AES-256-GCM. Ключ получается из пароля через PBKDF2-HMAC-SHA256,
600 000 итераций (норма OWASP на 2023 год).

Почему не «просто зашифровать паролем»: у AES есть проверка
целостности, и при неверном пароле программа скажет «пароль неверен»,
а не выдаст повреждённый файл. Разница принципиальная: испорченный
файл можно обнаружить только по факту, когда он уже не пригодился.

ЧТО НЕ ДЕЛАЕТ

  - не отправляет ничего в интернет, файлы никуда не копирует;
  - не хранит пароль нигде — только в голове;
  - не удаляет исходный файл сам: это опасная операция, решение
    за пользователем.

ТРЕБОВАНИЯ

Python 3 и cryptography. cryptography уже стоит — ею пользуется
генератор ключей SORA. Ничего устанавливать не нужно.
"""

from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ИТЕРАЦИИ = 600_000
РАЗМЕР_СОЛИ = 16
РАЗМЕР_КЛЮЧА = 32       # AES-256
РАЗМЕР_НОНСА = 12       # стандартный для GCM
РАЗМЕР_БЛОКА = 1024 * 1024

РАСШИРЕНИЕ = ".enc"


def вывести_ключ(пароль: bytes, соль: bytes) -> bytes:
    """Из пароля сделать ключ AES-256."""
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(),
        length=РАЗМЕР_КЛЮЧА,
        salt=соль,
        iterations=ИТЕРАЦИИ,
    )
    return kdf.derive(пароль)


def спросить_пароль(для_расшифровки: bool = False) -> bytes:
    """
    Получить пароль от человека.

    При шифровании спрашиваем дважды: опечатку на мигающем экране
    делают легко, а потерянный пароль означает потерянные ключи.
    """
    if для_расшифровки:
        import getpass
        пароль = getpass.getpass("Пароль: ")
        return пароль.encode("utf-8")

    первый = input("Придумайте пароль: ")
    if not первый:
        print("  пустой пароль не подойдёт")
        raise SystemExit(1)

    if len(первый) < 8:
        print()
        print("  ВНИМАНИЕ: пароль короче 8 символов.")
        print("  Перебор такого пароля — минуты, а не годы.")
        ответ = input("  Всё равно продолжить? (д/н): ").strip().lower()
        if ответ not in ("д", "да", "y", "yes"):
            print("  Отменено.")
            raise SystemExit(1)

    второй = input("Повторите пароль: ")
    if первый != второй:
        print()
        print("  Пароли не совпадают. Ничего не изменено.")
        raise SystemExit(1)

    return первый.encode("utf-8")


def зашифровать(исходник: Path, пароль: bytes) -> Path:
    """
    Зашифровать файл целиком.

    Файл маленький (реестр — меньше 2 КБ), поэтому читаем его
    целиком. Для крупных файлов поток шифруется блоками, смётка
    та же, но память не растёт.
    """
    соль = secrets.token_bytes(РАЗМЕР_СОЛИ)
    нонс = secrets.token_bytes(РАЗМЕР_НОНСА)
    ключ = вывести_ключ(пароль, соль)

    данные = исходник.read_bytes()
    шифротекст = AESGCM(ключ).encrypt(нонс, данные, None)

    цель = исходник.with_name(исходник.name + РАСШИРЕНИЕ)
    цель.write_bytes(соль + нонс + шифротекст)

    return цель


def расшифровать(источник: Path, пароль: bytes) -> bytes:
    """Расшифровать и вернуть содержимое."""
    блоб = источник.read_bytes()
    нужно = РАЗМЕР_СОЛИ + РАЗМЕР_НОНСА

    if len(блоб) <= нужно:
        raise ValueError(
            "файл слишком мал, это не зашифрованный файл")

    соль = блоб[:РАЗМЕР_СОЛИ]
    нонс = блоб[РАЗМЕР_СОЛИ:нужно]
    шифротекст = блоб[нужно:]

    ключ = вывести_ключ(пароль, соль)

    try:
        return AESGCM(ключ).decrypt(нонс, шифротекст, None)
    except InvalidTag:
        raise ValueError(
            "неверный пароль либо файл повреждён") from None


def проверить_результат(исходник: Path, созданный: Path,
                        пароль: bytes) -> None:
    """
    Расшифровать только что созданный файл и сравнить с оригиналом.

    Зачем: если шифрование прошло с ошибкой, узнать об этом нужно
    сейчас, а не в тот день, когда файл понадобится. Тогда дешифровка
    не удастся, и данные потеряны безвозвратно.
    """
    try:
        обратно = расшифровать(созданный, пароль)
    except ValueError:
        print()
        print("  ПРОВЕРКА НЕ ПРОЙДЕНА — файл не расшифровывается обратно.")
        созданный.unlink(missing_ok=True)
        print("  Созданный файл удалён. Оригинал не тронут.")
        raise SystemExit(1)

    if обратно != исходник.read_bytes():
        print()
        print("  ПРОВЕРКА НЕ ПРОЙДЕНА — содержимое отличается.")
        созданный.unlink(missing_ok=True)
        print("  Созданный файл удалён. Оригинал не тронут.")
        raise SystemExit(1)


def показать_размер(число: int) -> str:
    """Человекочитаемый размер: 1 773 Б, 2,3 МБ."""
    if число < 1024:
        return f"{число} Б"
    if число < 1024 * 1024:
        return f"{число / 1024:.1f} КБ"
    return f"{число / 1024 / 1024:.2f} МБ"


def разобрать_путь(текст: str) -> Path:
    """Убрать кавычки, которые остаются при перетаскивании в консоль."""
    текст = текст.strip().strip('"').strip("'")
    путь = Path(текст)

    if not путь.exists():
        print(f"  Файла нет: {путь}")
        raise SystemExit(1)

    return путь


def действие_зашифровать() -> None:
    print()
    print("─" * 60)
    print("  ЗАШИФРОВАТЬ")
    print("─" * 60)
    print()
    путь = разобрать_путь(input("  Путь к файлу: "))
    пароль = спросить_пароль()

    цель = зашифровать(путь, пароль)
    проверить_результат(путь, цель, пароль)

    print()
    print("  [ok] Зашифровано и проверено.")
    print()
    print(f"  Откуда:  {путь.name}   {показать_размер(путь.stat().st_size)}")
    print(f"  Куда:    {цель.name}   {показать_размер(цель.stat().st_size)}")
    print()
    print("  Оригинал НЕ удалён. Удалить его — ваше решение.")


def действие_расшифровать() -> None:
    print()
    print("─" * 60)
    print("  РАСШИФРОВАТЬ")
    print("─" * 60)
    print()
    путь = разобрать_путь(input("  Путь к файлу .enc: "))
    пароль = спросить_пароль(для_расшифровки=True)

    try:
        данные = расшифровать(путь, пароль)
    except ValueError as ошибка:
        print()
        print(f"  Не получилось: {ошибка}")
        print("  Файл не тронут.")
        return

    имя = путь.name
    if имя.endswith(РАСШИРЕНИЕ):
        имя = имя[:-len(РАСШИРЕНИЕ)]

    цель = путь.with_name(имя + ".расшифровано")
    цель.write_bytes(данные)

    print()
    print("  [ok] Расшифровано.")
    print()
    print(f"  Откуда: {путь.name}   {показать_размер(путь.stat().st_size)}")
    print(f"  Куда:   {цель.name}   {показать_размер(цель.stat().st_size)}")
    print()
    print("  Зашифрованный файл НЕ удалён.")


